// Design: docs/architecture/wire/attributes.md — path attribute encoding
// RFC: rfc/short/rfc4271.md — ORIGIN attribute (Section 5.1.1)

package attribute

import (
	"fmt"

	bgpctx "github.com/ze-software/ze/internal/core/bgp/context"
	"github.com/ze-software/ze/internal/core/bgp/wire"
	"github.com/ze-software/ze/internal/core/textbuf"
)

// Origin represents the ORIGIN path attribute.
//
// RFC 4271 Section 4.3 (UPDATE Message Format):
//
//	"ORIGIN is a well-known mandatory attribute that defines the
//	origin of the path information."
//
// RFC 4271 Section 5.1.1 (ORIGIN):
//
//	"ORIGIN is a well-known mandatory attribute. The ORIGIN attribute is
//	generated by the speaker that originates the associated routing
//	information. Its value SHOULD NOT be changed by any other speaker."
//
// The attribute value is a single octet (1 byte).
type Origin uint8

// Origin values as defined in RFC 4271 Section 4.3:
//
//	Value   Meaning
//	0       IGP - Network Layer Reachability Information is interior to the originating AS
//	1       EGP - Network Layer Reachability Information learned via the EGP protocol [RFC904]
//	2       INCOMPLETE - Network Layer Reachability Information learned by some other means
const (
	OriginIGP        Origin = 0 // RFC 4271: interior to the originating AS
	OriginEGP        Origin = 1 // RFC 4271: learned via EGP [RFC904]
	OriginIncomplete Origin = 2 // RFC 4271: learned by some other means
)

var originNames = map[Origin]string{
	OriginIGP:        "IGP",
	OriginEGP:        "EGP",
	OriginIncomplete: "INCOMPLETE",
}

// originTextNames maps Origin values to lowercase wire/JSON names.
var originTextNames = map[Origin]string{
	OriginIGP:        "igp",
	OriginEGP:        "egp",
	OriginIncomplete: "incomplete",
}

// originFromText maps lowercase wire/JSON names to Origin values. DERIVED from
// originTextNames so the accepted spellings and the emitted ones cannot drift.
var originFromText = func() map[string]Origin {
	m := make(map[string]Origin, len(originTextNames))
	for value, name := range originTextNames {
		m[name] = value
	}
	return m
}()

// String returns the human-readable origin name ("IGP", "EGP", or "INCOMPLETE").
func (o Origin) String() string {
	if name, ok := originNames[o]; ok {
		return name
	}
	var b textbuf.Buffer
	return b.Reset().Str("UNKNOWN(").Int(int64(o)).Byte(')').String()
}

// MarshalText returns the lowercase wire/JSON name ("igp", "egp", "incomplete").
// Implements encoding.TextMarshaler for JSON wire compatibility.
func (o Origin) MarshalText() ([]byte, error) {
	if name, ok := originTextNames[o]; ok {
		return []byte(name), nil
	}
	return nil, fmt.Errorf("unknown origin value %d", o)
}

// UnmarshalText parses a lowercase wire/JSON name ("igp", "egp", "incomplete").
// Implements encoding.TextUnmarshaler for JSON wire compatibility.
func (o *Origin) UnmarshalText(text []byte) error {
	v, ok := originFromText[string(text)]
	if !ok {
		return fmt.Errorf("unknown origin %q", text)
	}
	*o = v
	return nil
}

// LowerString returns the lowercase wire/JSON name ("igp", "egp", "incomplete").
// Returns "" for unknown values. This is a non-allocating accessor for hot paths
// that need the wire name without the MarshalText allocation.
func (o Origin) LowerString() string {
	if name, ok := originTextNames[o]; ok {
		return name
	}
	return ""
}

// Code returns AttrOrigin (Type Code 1 per RFC 4271 Section 4.3).
func (o Origin) Code() AttributeCode { return AttrOrigin }

// Flags returns FlagTransitive.
//
// RFC 4271 Section 4.3: "ORIGIN is a well-known mandatory attribute"
// Well-known attributes have the Transitive bit set.
func (o Origin) Flags() AttributeFlags { return FlagTransitive }

// Len returns 1.
//
// RFC 4271 Section 4.3: "The data octet can assume the following values"
// The ORIGIN attribute is always exactly 1 octet.
func (o Origin) Len() int { return 1 }

// WriteTo writes the origin value into buf at offset.
// Returns 1 (number of bytes written).
func (o Origin) WriteTo(buf []byte, off int) int {
	buf[off] = byte(o)
	return 1
}

// WriteToWithContext writes the origin value - context-independent.
func (o Origin) WriteToWithContext(buf []byte, off int, _, _ *bgpctx.EncodingContext) int {
	return o.WriteTo(buf, off)
}

// CheckedWriteTo validates capacity before writing.
// Returns ErrBufferTooSmall if buffer is insufficient.
func (o Origin) CheckedWriteTo(buf []byte, off int) (int, error) {
	if len(buf) < off+1 {
		return 0, wire.ErrBufferTooSmall
	}
	return o.WriteTo(buf, off), nil
}

// ParseOrigin parses an ORIGIN attribute value.
//
// RFC 4271 Section 6.3 (UPDATE Message Error Handling):
//
//	"If the ORIGIN attribute has an undefined value, then the Error Sub-
//	code MUST be set to Invalid Origin Attribute. The Data field MUST
//	contain the unrecognized attribute (type, length, and value)."
//
// Valid values are 0 (IGP), 1 (EGP), and 2 (INCOMPLETE) per Section 4.3.
func ParseOrigin(data []byte) (Origin, error) {
	if len(data) < 1 {
		return 0, ErrShortData
	}
	o := Origin(data[0])
	// RFC 4271 Section 6.3: undefined values trigger Invalid Origin Attribute error
	if o > OriginIncomplete {
		return 0, fmt.Errorf("%w: invalid origin value %d", ErrMalformedValue, o)
	}
	return o, nil
}

// OrderAttributes sorts attributes with MP_UNREACH first, then every remaining
// attribute -- MP_REACH included -- in ascending type-code order.
//
// Order: MP_UNREACH_NLRI (15) → all other attrs by type code, so MP_REACH (14)
// sits between CLUSTER_LIST (10) and EXT_COMMUNITIES (16).
//
// RFC 4271 Section 5 leaves the order free ("A BGP speaker MUST be prepared to
// accept attributes in any order"), so this is a house convention rather than a
// requirement -- which is precisely why it has to be ONE convention.
//
// It used to place MP_REACH LAST, on the rationale that the regular attributes
// describe the NLRI carried in MP_REACH. Reasonable in isolation, but this is one
// of three builders that emit the same route, and the other two put MP_REACH at
// its type-code position: reactor/peer_rib_routes.go buildRIBRouteUpdate (which
// slots it between writeOptionalAttrs(0,14) and writeOptionalAttrs(14,17)) and
// reactor/reactor_api_batch.go buildWireModeUpdate (insertAttrOrdered). A route
// therefore left the daemon as two different byte strings depending on which
// builder produced it, and an exact-hex functional test became a test of the rail
// rather than of the route: test/plugin/flowspec.ci asserted EXT_COMMUNITIES
// before MP_REACH because a static config route produced its bytes, while the
// same route sent through `update text` produced the reverse.
//
// peer_rib_routes.go's own ordering note already CLAIMED this function sorted by
// type code. It now does, and the claim is true.
//
// MP_UNREACH stays first, out of type-code order, deliberately: a withdrawal
// logically precedes an announcement in the same message.
//
// The function returns a new slice; the original is not modified.
// If the input is nil, nil is returned.
// If the input is empty, an empty slice is returned.
func OrderAttributes(attrs []Attribute) []Attribute {
	if attrs == nil {
		return nil
	}
	if len(attrs) == 0 {
		return []Attribute{}
	}
	if len(attrs) == 1 {
		return attrs
	}

	// Separate MP_UNREACH only. MP_REACH sorts with everything else, by code.
	var regular []Attribute
	var mpUnreach Attribute

	for _, attr := range attrs {
		if attr.Code() == AttrMPUnreachNLRI {
			mpUnreach = attr
			continue
		}
		regular = append(regular, attr)
	}

	// Sort regular attributes by type code using insertion sort (stable, good for small slices)
	for i := 1; i < len(regular); i++ {
		key := regular[i]
		j := i - 1
		for j >= 0 && regular[j].Code() > key.Code() {
			regular[j+1] = regular[j]
			j--
		}
		regular[j+1] = key
	}

	// Build result: UNREACH + everything else in type-code order.
	result := make([]Attribute, 0, len(attrs))
	if mpUnreach != nil {
		result = append(result, mpUnreach)
	}
	result = append(result, regular...)

	return result
}

// WriteAttributesOrdered writes attributes ordered by type code into buf.
// Returns the number of bytes written.
//
// RFC 4271 Appendix F.3: Order by type code for efficient comparison.
// Zero-allocation: writes directly into provided buffer.
func WriteAttributesOrdered(attrs []Attribute, buf []byte, off int) int {
	if len(attrs) == 0 {
		return 0
	}

	ordered := OrderAttributes(attrs)
	start := off
	for _, attr := range ordered {
		off += WriteAttrTo(attr, buf, off)
	}

	return off - start
}

// AttributesSize calculates the total wire size of attributes (header + value).
// Used for pre-allocating buffers before calling WriteAttributesOrdered.
func AttributesSize(attrs []Attribute) int {
	totalLen := 0
	for _, attr := range attrs {
		attrLen := attr.Len()
		if attrLen > 255 {
			totalLen += 4 + attrLen // Extended length header
		} else {
			totalLen += 3 + attrLen // Normal header
		}
	}
	return totalLen
}

// AttributesSizeWithContext calculates the total wire size with context-dependent encoding.
// Context affects AS_PATH (ASN4 encoding) and AGGREGATOR (6 vs 8 byte format).
// Used for pre-allocating buffers before calling WriteAttrToWithContext.
func AttributesSizeWithContext(attrs []Attribute, ctx *bgpctx.EncodingContext) int {
	totalLen := 0
	for _, attr := range attrs {
		attrLen := attrLenWithContext(attr, ctx)
		if attrLen > 255 {
			totalLen += 4 + attrLen // Extended length header
		} else {
			totalLen += 3 + attrLen // Normal header
		}
	}
	return totalLen
}
