// selectFixture commits head at path, selects the hunk mine adds against it
// while the working tree holds both, and answers the selection.
func selectFixture(t *testing.T, root, path, head, mine, both string) hunks.Selection {
	t.Helper()
	commitFixture(t, root, "base "+path, map[string]string{path: head}, nil)
	patch := writeHunkPatch(t, root, path, mine, both)
	entry, err := hunks.Apply(root, headOf(t, root), path, patch)
	if err != nil {
		t.Fatal(err)
	}
	return hunks.Selection{path: {Entry: entry, Patch: patch}}
}

// TestClosureStemHunksJudgesSelectedOwner proves the owned-row guard reads a
// hunks spec through the selection: the commit adds an open row, and the
// spec's owner entry for it sits in a hunk the commit does not carry, so the
// row is unowned in what lands and the commit is refused.
//
// VALIDATES: closureStemSelected refuses with the owned-rows refusal.
// PREVENTS: an owner entry only the working tree holds admitting a row.
func TestClosureStemHunksJudgesSelectedOwner(t *testing.T) {
	root := newCommitRepository(t)
	configureCommitAuthor(t, root)
	commitFixture(t, root, "journal", map[string]string{
		"plan/journal/README.md": "# Journal\n",
		hunkClassPath:            "# Silent default\n\n" + hunkTableHead,
	}, nil)
	head := "# Spec\n\n## Owned journal rows\n\n| Class file | Date | Surface (short) |\n|---|---|---|\n\n## Notes\n\n" + hunkPadding
	both := strings.Replace(head, "|---|---|---|\n", "|---|---|---|\n"+hunkOwnerEntry, 1) + "mine\n"
	selection := selectFixture(t, root, hunkSpecPath, head, head+"mine\n", both)
	writeCommitFixture(t, root, hunkClassPath, "# Silent default\n\n"+hunkTableHead+hunkOpenRow)

	_, err := closureStemSelected(root, []string{hunkClassPath, hunkSpecPath}, nil, specjournal.Base{}, selection)
	if err == nil || !strings.Contains(err.Error(), "owned journal rows") {
		t.Fatalf("an owner entry outside the selected hunks: %v, want the owned-rows refusal", err)
	}
	if _, err := closureStem(root, []string{hunkClassPath, hunkSpecPath}, nil, specjournal.Base{}); err != nil {
		t.Fatalf("the whole spec carries the owner, yet closureStem refused: %v", err)
	}
}

// TestClosureStemHunksIgnoresForeignRow proves the reverse: a hunks class
// file whose working tree holds another session's unowned open row, outside
// the selected hunk, is judged on the selected blob and admitted.
//
// VALIDATES: closureStemSelected admits; the whole file is refused.
// PREVENTS: a foreign row the commit does not carry refusing it.
func TestClosureStemHunksIgnoresForeignRow(t *testing.T) {
	root := newCommitRepository(t)
	configureCommitAuthor(t, root)
	commitFixture(t, root, "readme", map[string]string{"plan/journal/README.md": "# Journal\n"}, nil)
	var fixed strings.Builder
	for day := 10; day < 20; day++ {
		fixed.WriteString("| 2026-01-" + string(rune('0'+day/10)) + string(rune('0'+day%10)) + " | - | cli | old | fixed: done |\n")
	}
	head := "# Silent default\n\n" + hunkTableHead + fixed.String()
	mineRow := "| 2026-10-24 | - | cli | mine | fixed: repaired |\n"
	both := "# Silent default\n\n" + hunkTableHead + hunkOpenRow + fixed.String() + mineRow
	selection := selectFixture(t, root, hunkClassPath, head, head+mineRow, both)

	if _, err := closureStemSelected(root, []string{hunkClassPath}, nil, specjournal.Base{}, selection); err != nil {
		t.Fatalf("the selected hunk adds a fixed row only, yet the guard refused: %v", err)
	}
	if _, err := closureStem(root, []string{hunkClassPath}, nil, specjournal.Base{}); err == nil {
		t.Fatal("the whole file carries the foreign open row, yet closureStem admitted it: the fixture proves nothing")
	}
}

// TestCoverageHunksJudgesSelectedBlob proves test coverage reads a hunks Go
// file through the selection: another session's hunk marks the file
// generated, which would exempt it, and the selected blob is not generated.
func TestCoverageHunksJudgesSelectedBlob(t *testing.T) {
	root := newCommitRepository(t)
	configureCommitAuthor(t, root)
	const path = "pkg/shared.go"
	head := "package pkg\n\n// " + strings.ReplaceAll(strings.TrimSpace(hunkPadding), "\n", "\n// ") + "\n"
	mine := head + "\nfunc Mine() {}\n"
	both := "// Code generated by fixture. DO NOT EDIT.\n\n" + mine
	selection := selectFixture(t, root, path, head, mine, both)

	if problems := mustCoverage(t, root, []string{path}, selection); len(problems) == 0 {
		t.Fatal("the selected blob is hand-written Go with no test, yet coverage owed nothing")
	}
	if problems := mustCoverage(t, root, []string{path}, nil); len(problems) != 0 {
		t.Fatalf("the working tree is generated, yet coverage owed %v: the fixture proves nothing", problems)
	}
}

// TestRFCChangeHunksJudgesSelectedBlob proves the RFC-tagged change gate
// reads a hunks test file through the selection: another session's hunk
// changes the tagged unit, the selected hunk does not, so the commit needs no
// approval, while the whole file does.
func TestRFCChangeHunksJudgesSelectedBlob(t *testing.T) {
	root := newCommitRepository(t)
	t.Setenv("CLAUDE_CODE_SESSION_ID", "hunks-rfc-fixture")
	configureCommitAuthor(t, root)
	head := taggedUnitText("check(1)") + "\n// " + strings.ReplaceAll(strings.TrimSpace(hunkPadding), "\n", "\n// ") + "\n"
	mine := head + "// mine\n"
	both := strings.Replace(mine, "check(1)", "check(2)", 1)
	commitFixture(t, root, "tagged", map[string]string{approvalTagged: head}, nil)
	patch := writeHunkPatch(t, root, approvalTagged, mine, both)
	options := func() *Options {
		return &Options{Session: approvalSession, Subject: "x", NoTest: "the fixture carries tests only", DryRun: true}
	}

	whole := options()
	whole.Files = []string{approvalTagged}
	if _, err := Create(root, whole); err == nil || !strings.Contains(err.Error(), "TestThing") {
		t.Fatalf("the whole file changes the tagged unit: %v, want the RFC-tagged refusal", err)
	}
	selected := options()
	selected.Hunks = []HunkSelection{{Path: approvalTagged, Patch: patch}}
	if _, err := Create(root, selected); err != nil {
		t.Fatalf("the selected hunk leaves the tagged unit alone, yet Create refused: %v", err)
	}
}

