// mustCoverage is testCoverageProblemsSelected for a fixture every path of
// which is readable.
func mustCoverage(t *testing.T, root string, paths []string, selection hunks.Selection) []string {
	t.Helper()
	problems, err := testCoverageProblemsSelected(root, paths, selection)
	if err != nil {
		t.Fatal(err)
	}
	return problems
}

// reviewRepinFixture commits a hunks path whose name holds a space and one
// other code file, selects this session's hunk, and answers both paths.
func reviewRepinFixture(t *testing.T) (root, path, other string, selection hunks.Selection) {
	t.Helper()
	root = newCommitRepository(t)
	t.Setenv("CLAUDE_CODE_SESSION_ID", "hunks-review-record-fixture")
	configureCommitAuthor(t, root)
	path, other = "pkg/shared one.go", "pkg/other.go"
	commitFixture(t, root, "base", map[string]string{path: hunkBase, other: "package pkg\n"}, nil)
	writeCommitFixture(t, root, other, "package pkg\n\n// Changed.\n")
	writeCommitFixture(t, root, "docs/extra.md", "# Extra\n")
	patch := writeHunkPatch(t, root, path, hunkMine, hunkBoth)
	entry, err := hunks.Apply(root, headOf(t, root), path, patch)
	if err != nil {
		t.Fatal(err)
	}
	return root, path, other, hunks.Selection{path: {Entry: entry, Patch: patch}}
}

// recordFixtureReview runs `le spec review record` through the real recorder.
func recordFixtureReview(t *testing.T, root string, args ...string) {
	t.Helper()
	// The recorder resolves the checkout through env, which caches: without
	// the reset it records into the checkout the test runs in.
	t.Setenv("ZE_REPO_ROOT", root)
	env.ResetCache()
	t.Cleanup(env.ResetCache)
	if payload, code := spec.Review(append([]string{"record"}, args...)); code != 0 {
		t.Fatalf("review record %q = (%#v, %d)", args, payload, code)
	}
}

// repinCommand answers the record command a refusal ends with. A quoted
// value may span lines, so the command runs to the end of its problem.
func repinCommand(t *testing.T, result ReviewResult) string {
	t.Helper()
	const marker = "\n  ./le spec review record "
	for _, problem := range result.Problems {
		if index := strings.Index(problem, marker); index >= 0 {
			return problem[index+3:]
		}
	}
	t.Fatalf("the refusal prints no record command: %v", result.Problems)
	return ""
}

// artifactBody answers the demo review artifact below its header line.
func artifactBody(t *testing.T, root string) string {
	t.Helper()
	relative, err := spec.ReviewArtifactPath(root, "demo")
	if err != nil {
		t.Fatal(err)
	}
	content, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(relative)))
	if err != nil {
		t.Fatal(err)
	}
	_, body, _ := strings.Cut(string(content), "\n")
	return body
}

func patchOf(selection hunks.Selection, path string) string {
	return selection[path].Patch
}
