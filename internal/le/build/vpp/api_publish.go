// Design: third_party/vpp-patches/README.md -- publish only generated API files.
// Related: api.go -- the complete generator must succeed before publication.
package buildvpp

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

const apiGeneratedHeader = "// Code generated by GoVPP's binapi-generator. DO NOT EDIT."

// apiCheckOutput refuses symlink ancestors and files another producer owns.
// It checks the fixed four outputs only. Other package files are preserved.
func apiCheckOutput(root string) error {
	for _, name := range apiPackageNames() {
		if err := apiCheckPackageOutput(root, name); err != nil {
			return err
		}
	}
	return nil
}

func apiCheckPackageOutput(root, name string) error {
	output := filepath.Join(apiOutputRoot, name)
	current := root
	for _, part := range strings.Split(filepath.ToSlash(output), "/") {
		current = filepath.Join(current, part)
		info, err := os.Lstat(current)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("the generated API directory uses a symbolic link: %s", current)
		}
		if !info.IsDir() {
			return fmt.Errorf("the generated API directory is not a directory: %s", current)
		}
	}
	for _, name := range apiPackageFiles(name) {
		path := filepath.Join(root, output, name)
		info, err := os.Lstat(path)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return err
		}
		if !info.Mode().IsRegular() {
			return fmt.Errorf("the generated API output is not a regular file: %s", path)
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(data, []byte(apiGeneratedHeader+"\n")) {
			return fmt.Errorf("the API generator does not own %s. Preserve that file before generating bindings", path)
		}
	}
	return nil
}

func apiPublish(root, source string) ([]string, error) {
	// All four inputs and both schemas are checked before any canonical
	// output changes. A malformed second package cannot replace the first.
	type publication struct {
		path string
		data []byte
	}
	outputs := make([]publication, 0, 4)
	for _, packageName := range apiPackageNames() {
		for _, name := range apiPackageFiles(packageName) {
			path := filepath.Join(source, packageName, name)
			content, err := os.ReadFile(path)
			if err != nil {
				return nil, err
			}
			parsed, err := parser.ParseFile(token.NewFileSet(), path, content, parser.ParseComments)
			if err != nil {
				return nil, err
			}
			if parsed.Name.Name != packageName {
				return nil, fmt.Errorf("the API generator produced package %s instead of %s", parsed.Name.Name, packageName)
			}
			if !bytes.HasPrefix(content, []byte(apiGeneratedHeader+"\n")) {
				return nil, fmt.Errorf("the API generator produced an unowned file: %s", name)
			}
			if name == packageName+".ba.go" {
				if packageName == "pppoe" {
					if err := apiCheckSchema(parsed); err != nil {
						return nil, err
					}
				} else {
					if err := apiCheckFeatureSchema(parsed); err != nil {
						return nil, err
					}
				}
			}
			outputs = append(outputs, publication{path: filepath.Join(apiOutputRoot, packageName, name), data: content})
		}
	}
	if err := apiCheckOutput(root); err != nil {
		return nil, err
	}
	files := make([]string, 0, len(outputs))
	for _, output := range outputs {
		path := filepath.Join(root, output.path)
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			return nil, err
		}
		if err := apiWriteOutput(path, output.data); err != nil {
			return nil, err
		}
		files = append(files, filepath.ToSlash(output.path))
	}
	return files, nil
}

func apiPackageFiles(name string) []string { return []string{name + ".ba.go", name + "_rpc.ba.go"} }

func apiCheckSchema(file *ast.File) error {
	fields := apiSchemaFields(file)
	for _, required := range []struct{ message, field string }{
		{"PppoeAddDelSession", "DisableFib"},
		{"PppoeAddDelCp", "CpSwIfIndex"},
		{"PppoeAddDelCp", "DpSwIfIndex"},
		{"PppoeCpBindingDump", "SwIfIndex"},
		{"PppoeCpBindingDetails", "CpSwIfIndex"},
		{"PppoeCpBindingDetails", "DpSwIfIndex"},
	} {
		if fields[required.message][required.field] == nil {
			return fmt.Errorf("the generated PPPoE API lacks %s.%s. The retained patches did not produce the required API", required.message, required.field)
		}
	}
	return nil
}

func apiCheckFeatureSchema(file *ast.File) error {
	fields := apiSchemaFields(file)
	for _, required := range []struct{ message, field, kind string }{
		{"FeatureEnableDisable", "SwIfIndex", "interface_types.InterfaceIndex"},
		{"FeatureEnableDisable", "Enable", "bool"},
		{"FeatureEnableDisable", "ArcName", "string"},
		{"FeatureEnableDisable", "FeatureName", "string"},
		{"FeatureEnableDisableReply", "Retval", "int32"},
		{"FeatureIsEnabled", "SwIfIndex", "interface_types.InterfaceIndex"},
		{"FeatureIsEnabled", "ArcName", "string"},
		{"FeatureIsEnabled", "FeatureName", "string"},
		{"FeatureIsEnabledReply", "Retval", "int32"},
		{"FeatureIsEnabledReply", "IsEnabled", "bool"},
	} {
		if apiFieldType(fields[required.message][required.field]) != required.kind {
			return fmt.Errorf("the generated Feature API lacks %s.%s with type %s. Regenerate from the pinned VPP source", required.message, required.field, required.kind)
		}
	}
	return nil
}

func apiSchemaFields(file *ast.File) map[string]map[string]ast.Expr {
	fields := make(map[string]map[string]ast.Expr)
	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range general.Specs {
			declaration, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			structure, ok := declaration.Type.(*ast.StructType)
			if !ok {
				continue
			}
			members := make(map[string]ast.Expr)
			for _, field := range structure.Fields.List {
				for _, name := range field.Names {
					members[name.Name] = field.Type
				}
			}
			fields[declaration.Name.Name] = members
		}
	}
	return fields
}

func apiFieldType(field ast.Expr) string {
	if name, ok := field.(*ast.Ident); ok {
		return name.Name
	}
	if selector, ok := field.(*ast.SelectorExpr); ok {
		if qualifier, ok := selector.X.(*ast.Ident); ok {
			return qualifier.Name + "." + selector.Sel.Name
		}
	}
	// The schema accepts only named scalar fields; nil and composite types
	// deliberately cannot match any required scalar name.
	return ""
}

// apiWriteOutput stages beside the destination so rename is atomic on the
// destination filesystem. The caller MUST check ownership before this write.
func apiWriteOutput(path string, data []byte) (retErr error) {
	file, err := os.CreateTemp(filepath.Dir(path), ".vpp-api-")
	if err != nil {
		return err
	}
	defer func() {
		if err := os.Remove(file.Name()); err != nil {
			if !errors.Is(err, os.ErrNotExist) {
				retErr = errors.Join(retErr, err)
			}
		}
	}()
	_, writeErr := file.Write(data)
	closeErr := file.Close()
	if err := errors.Join(writeErr, closeErr); err != nil {
		return err
	}
	return os.Rename(file.Name(), path)
}
