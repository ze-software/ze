func TestVPPAPIGenerationPublishesPatchedBindings(t *testing.T) {
	root, scratch := apiFixture(t)
	docker := &apiDockerFixture{}
	process := &apiProcessFixture{}
	report, err := generateAPI(t.Context(), root, scratch, docker, process, []string{"CGO_ENABLED=0"})
	if err != nil {
		t.Fatal(err)
	}
	if report.Generator != "go.fd.io/govpp/cmd/binapi-generator@v0.13.0" {
		t.Fatalf("generator = %q", report.Generator)
	}
	if !slices.Contains(docker.build.BuildArgs, "VPP_COMMIT=fixture-commit") {
		t.Fatalf("canonical pin not passed: %#v", docker.build)
	}
	if docker.build.Context == root {
		t.Fatal("whole checkout sent to Docker")
	}
	if docker.released != 1 {
		t.Fatalf("released %d image leases", docker.released)
	}
	if docker.reads != 6 {
		t.Fatalf("read %d JSON inputs", docker.reads)
	}
	if !slices.Contains(process.command.Arguments, "--import-prefix=go.fd.io/govpp/binapi") {
		t.Fatalf("unexpected dependency imports: %#v", process.command)
	}
	if !slices.Contains(process.command.Environment, "CGO_ENABLED=0") {
		t.Fatal("generator has no explicit CGO policy")
	}
	if !slices.Equal(process.command.Arguments[:4], []string{"go", "run", "-mod=mod", "go.fd.io/govpp/cmd/binapi-generator@v0.13.0"}) {
		t.Fatalf("generator command = %v", process.command.Arguments)
	}
	if process.command.Timeout <= 0 {
		t.Fatal("generator has no time bound")
	}
	for _, name := range []string{"pppoe.ba.go", "pppoe_rpc.ba.go"} {
		data, err := os.ReadFile(filepath.Join(root, apiOutput, name))
		if err != nil {
			t.Fatal(err)
		}
		if !strings.HasPrefix(string(data), "// Code generated by GoVPP") {
			t.Fatalf("%s is not generated", name)
		}
	}
	entries, err := os.ReadDir(scratch)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 0 {
		t.Fatalf("private intermediates retained: %v", entries)
	}
}

func TestVPPAPIGeneratorFailurePreservesCanonicalFiles(t *testing.T) {
	root, scratch := apiFixture(t)
	path := filepath.Join(root, apiOutput, "pppoe.ba.go")
	apiWriteFixture(t, path, "// Code generated by GoVPP's binapi-generator. DO NOT EDIT.\npackage pppoe\n// original\n")
	docker := &apiDockerFixture{}
	process := &apiProcessFixture{code: 23}
	_, err := generateAPI(t.Context(), root, scratch, docker, process, []string{"CGO_ENABLED=0"})
	if err == nil {
		t.Fatal("generator exit 23 was accepted")
	}
	if !strings.Contains(err.Error(), "23") {
		t.Fatalf("exit status lost: %v", err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), "// original") {
		t.Fatal("failed generation changed canonical output")
	}
	if docker.released != 1 {
		t.Fatalf("released %d leases on generator failure", docker.released)
	}
	entries, err := os.ReadDir(scratch)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 0 {
		t.Fatal("failed generation left intermediates")
	}
}

func TestVPPAPIJSONFailureCleansLeaseBeforeGenerator(t *testing.T) {
	root, scratch := apiFixture(t)
	ctx, cancel := context.WithCancel(t.Context())
	defer cancel()
	want := errors.New("container canceled during JSON read")
	docker := &apiDockerFixture{readError: want, cancelOnRead: cancel}
	process := &apiProcessFixture{}
	_, err := generateAPI(ctx, root, scratch, docker, process, []string{"CGO_ENABLED=0"})
	if !errors.Is(err, want) {
		t.Fatalf("JSON failure = %v", err)
	}
	if !errors.Is(ctx.Err(), context.Canceled) {
		t.Fatal("fixture never canceled generation")
	}
	if process.runs != 0 {
		t.Fatal("generator ran with incomplete JSON")
	}
	if docker.released != 1 {
		t.Fatal("JSON failure leaked image lease")
	}
	if docker.releaseContext.Err() != nil {
		t.Fatal("lease cleanup inherited cancellation")
	}
}

