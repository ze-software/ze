func TestVPPAPIRefusesSymlinkOutputDirectory(t *testing.T) {
	root, scratch := apiFixture(t)
	output := filepath.Join(root, apiOutput)
	if err := os.MkdirAll(filepath.Dir(output), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(t.TempDir(), output); err != nil {
		t.Fatal(err)
	}
	docker := &apiDockerFixture{}
	_, err := generateAPI(t.Context(), root, scratch, docker, &apiProcessFixture{}, []string{"CGO_ENABLED=0"})
	if err == nil {
		t.Fatal("output escaped through a symbolic link")
	}
	if docker.build.Context != "" {
		t.Fatal("source build started before output ownership refusal")
	}
}

func apiFixture(t *testing.T) (string, string) {
	t.Helper()
	root := t.TempDir()
	apiWriteFixture(t, filepath.Join(root, "third_party/vpp-patches/Dockerfile"), "ARG VPP_COMMIT=fixture-commit\nARG VPP_SHA256=fixture-sha\n")
	apiWriteFixture(t, filepath.Join(root, "third_party/vpp-patches/Dockerfile.api"), "FROM fixture\n")
	for _, name := range []string{"0001-fixture.patch", "ze/0001-fixture.patch"} {
		apiWriteFixture(t, filepath.Join(root, "third_party/vpp-patches", name), "fixture patch\n")
	}
	return root, t.TempDir()
}

func apiWriteFixture(t *testing.T, path, data string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(data), 0o600); err != nil {
		t.Fatal(err)
	}
}

type apiDockerFixture struct {
	build          interoplab.ImageBuild
	reads          int
	inputs         []string
	released       int
	readError      error
	buildError     error
	releaseError   error
	releaseContext context.Context
	cancelOnRead   context.CancelFunc
}

func (d *apiDockerFixture) Build(_ context.Context, build interoplab.ImageBuild) (interoplab.ImageResult, error) {
	d.build = build
	if d.buildError != nil {
		return interoplab.ImageResult{}, d.buildError
	}
	return interoplab.ImageResult{Reference: "sha256:api-fixture", Built: true}, nil
}

func (d *apiDockerFixture) ReleaseImage(ctx context.Context, _ interoplab.ImageResult) error {
	d.released++
	d.releaseContext = ctx
	return d.releaseError
}

func (d *apiDockerFixture) RunOneShot(_ context.Context, spec interoplab.OneShotContainer) (interoplab.CommandResult, error) {
	d.reads++
	if spec.Image != "sha256:api-fixture" {
		return interoplab.CommandResult{}, errors.New("JSON read did not use immutable built image")
	}
	if spec.Network != "none" {
		return interoplab.CommandResult{}, errors.New("JSON extraction has network access")
	}
	if len(spec.Command) != 2 {
		return interoplab.CommandResult{}, errors.New("JSON extraction has an unexpected command")
	}
	if spec.Command[0] != "cat" {
		return interoplab.CommandResult{}, errors.New("JSON extraction did not read image output")
	}
	d.inputs = append(d.inputs, spec.Command[1])
	if d.cancelOnRead != nil {
		d.cancelOnRead()
	}
	if d.readError != nil {
		return interoplab.CommandResult{}, d.readError
	}
	_, err := io.WriteString(spec.Stdout, "{\"messages\":[]}\n")
	return interoplab.CommandResult{}, err
}

type apiProcessFixture struct {
	command interoplab.ProcessCommand
	code    int
	runs    int
	stock   bool
}

func (p *apiProcessFixture) Run(_ context.Context, command interoplab.ProcessCommand) (interoplab.ProcessResult, error) {
	p.runs++
	p.command = command
	for _, arg := range command.Arguments {
		if !strings.HasPrefix(arg, "--output-dir=") {
			continue
		}
		output := strings.TrimPrefix(arg, "--output-dir=")
		if err := os.MkdirAll(filepath.Join(output, "pppoe"), 0o750); err != nil {
			return interoplab.ProcessResult{}, err
		}
		for _, name := range []string{"pppoe.ba.go", "pppoe_rpc.ba.go"} {
			data := "// Code generated by GoVPP's binapi-generator. DO NOT EDIT.\npackage pppoe\ntype PppoeAddDelSession struct { DisableFib bool }\ntype PppoeAddDelCp struct { CpSwIfIndex uint32; DpSwIfIndex uint32 }\ntype PppoeCpBindingDump struct { SwIfIndex uint32 }\ntype PppoeCpBindingDetails struct { CpSwIfIndex uint32; DpSwIfIndex uint32 }\n"
			if p.stock {
				data = "// Code generated by GoVPP's binapi-generator. DO NOT EDIT.\npackage pppoe\n"
			}
			if err := os.WriteFile(filepath.Join(output, "pppoe", name), []byte(data), 0o600); err != nil {
				return interoplab.ProcessResult{}, err
			}
		}
		if slices.Contains(command.Arguments, "feature") {
			if err := os.MkdirAll(filepath.Join(output, "feature"), 0o750); err != nil {
				return interoplab.ProcessResult{}, err
			}
			for _, name := range []string{"feature.ba.go", "feature_rpc.ba.go"} {
				if err := os.WriteFile(filepath.Join(output, "feature", name), []byte(apiFeatureFixture()), 0o600); err != nil {
					return interoplab.ProcessResult{}, err
				}
			}
		}
	}
	return interoplab.ProcessResult{ExitCode: p.code}, nil
}
