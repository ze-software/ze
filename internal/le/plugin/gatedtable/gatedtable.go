// Design: docs/architecture/plugin/feature-gates.md -- the generated gated-plugin table
// Related: report.go -- what the check and the write answer
// Related: actions.go -- the command surface
//
// Package gatedtable generates internal/component/plugin/registry/gated_plugins_gen.go,
// the always-compiled table of every plugin a build can compile out and the
// build tags that carry it.
//
// No binary can name a plugin it was built without, because the plugin's
// registration is compiled out with it. le is built with every feature tag, so
// it links every registration: this generator joins each registration's name
// and package directory (repoinventory.Plugins) with the manifest's gates
// (pluginimports.GateIndex, over repofeaturetags.Gates) and writes the answer
// into a file no build tag removes.
//
// The tags a row carries are the ones the composition root's //go:build line
// states for that plugin's import, from the same function, so the table cannot
// disagree with what actually links the plugin.
package gatedtable

import (
	"bytes"
	"errors"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/ze-software/ze/internal/core/textbuf"
	pluginimports "github.com/ze-software/ze/internal/le/plugin/imports"
	repoinventory "github.com/ze-software/ze/internal/le/repo/inventory"
)

// tableFile is the generated table, relative to the tree.
const tableFile = "internal/component/plugin/registry/gated_plugins_gen.go"

// generatedMarker names the native command that reproduces the file.
const generatedMarker = "// Code generated by ./le plugin gated-table write; DO NOT EDIT."

// Row is one gated plugin: its registered name, the package it registers from,
// every build tag that must be set for a binary to carry it (enclosing gates
// first, its own gate last), and the config roots it owns
// (Registration.ConfigRoots). The roots are what lets a build without the
// plugin name the tag when the operator writes one of them.
type Row struct {
	Name        string   `json:"name"`
	SourceDir   string   `json:"source-dir"`
	Tags        []string `json:"tags"`
	ConfigRoots []string `json:"config-roots,omitempty"`
}

// Derive answers every gated plugin this binary registers, sorted by name.
// A plugin whose package no manifest row gates is absent, because every build
// carries it.
func Derive(root string) ([]Row, error) {
	gates, err := pluginimports.LoadGateIndex(root)
	if err != nil {
		return nil, err
	}

	plugins, err := repoinventory.Plugins(root)
	if err != nil {
		return nil, err
	}

	return rowsOf(gates, plugins), nil
}

// rowsOf keeps the gated plugins and orders them by name, so two runs over one
// tree write the same bytes.
func rowsOf(gates pluginimports.GateIndex, plugins []repoinventory.Plugin) []Row {
	rows := make([]Row, 0, len(plugins))
	for i := range plugins {
		tags := gates.Requirement(plugins[i].SourceDir)
		if len(tags) == 0 {
			continue
		}
		roots := slices.Clone(plugins[i].ConfigRoots)
		slices.Sort(roots)
		rows = append(rows, Row{Name: plugins[i].Name, SourceDir: plugins[i].SourceDir, Tags: tags, ConfigRoots: roots})
	}
	slices.SortFunc(rows, func(a, b Row) int { return strings.Compare(a.Name, b.Name) })

	return rows
}

// render answers the gofmt-formatted source of the table.
func render(rows []Row) ([]byte, error) {
	var b textbuf.Buffer

	b.Str("// Design: docs/architecture/plugin/feature-gates.md -- the generated gated-plugin table\n")
	b.Str("// Related: gated_plugins.go -- GatedPluginTags, the lookup over this table\n//\n")
	b.Str(generatedMarker).Str("\n\n")
	b.Str("package registry\n\n")
	b.Str("// gatedPluginTags maps every plugin a build can compile out to the build tags\n")
	b.Str("// that must all be set for a binary to carry it, as feature-gates.txt declares\n")
	b.Str("// them. No build tag removes this file, so a binary built without a plugin can\n")
	b.Str("// still name the tag that would carry it.\n")
	b.Str("var gatedPluginTags = map[string][]string{\n")
	for _, row := range rows {
		b.Byte('\t').Str(strconv.Quote(row.Name)).Str(": {")
		for i, tag := range row.Tags {
			if i > 0 {
				b.Str(", ")
			}
			b.Str(strconv.Quote(tag))
		}
		b.Str("},\n")
	}
	b.Str("}\n\n")
	renderConfigRoots(&b, rows)

	return format.Source(b.Bytes())
}

// renderConfigRoots writes the second table: every config root a gated plugin
// owns, to the gated plugins that own it, both sorted. A root two plugins own
// (bgp and bgp-rib both own `bgp`) lists both, so the refusal can name every
// build that would accept the root.
func renderConfigRoots(b *textbuf.Buffer, rows []Row) {
	owners := make(map[string][]string)
	for _, row := range rows {
		for _, root := range row.ConfigRoots {
			owners[root] = append(owners[root], row.Name)
		}
	}
	roots := slices.Sorted(maps.Keys(owners))

	b.Str("// gatedConfigRoots maps every config root a gated plugin owns\n")
	b.Str("// (Registration.ConfigRoots) to the gated plugins that own it. A build\n")
	b.Str("// without those plugins has no schema node for the root, so the parser\n")
	b.Str("// reads this table to say which build tag would carry it.\n")
	b.Str("var gatedConfigRoots = map[string][]string{\n")
	for _, root := range roots {
		b.Byte('\t').Str(strconv.Quote(root)).Str(": {")
		for i, name := range owners[root] {
			if i > 0 {
				b.Str(", ")
			}
			b.Str(strconv.Quote(name))
		}
		b.Str("},\n")
	}
	b.Str("}\n")
}

// Check compares the table on disk with what the tree and this binary owe. A
// table that disagrees is a verdict in the report, not an error; a tree that
// cannot be read is an error.
func Check(root string) (CheckReport, error) {
	rows, want, err := owed(root)
	if err != nil {
		return CheckReport{}, err
	}

	reason, err := verdictOf(filepath.Join(root, filepath.FromSlash(tableFile)), want)
	if err != nil {
		return CheckReport{}, err
	}

	return CheckReport{File: tableFile, Rows: rows, Reason: reason}, nil
}

// Write regenerates the table and answers whether its bytes changed.
func Write(root string) (WriteReport, error) {
	rows, want, err := owed(root)
	if err != nil {
		return WriteReport{}, err
	}

	report := WriteReport{File: tableFile, Rows: rows}
	full := filepath.Join(root, filepath.FromSlash(tableFile))
	reason, err := verdictOf(full, want)
	if err != nil {
		return WriteReport{}, err
	}
	if reason == "" {
		return report, nil
	}
	if err := os.WriteFile(full, want, 0o644); err != nil { //nolint:gosec // generated source, read by the build
		return WriteReport{}, err
	}
	report.Written = true

	return report, nil
}

// owed answers the rows the tree owes and the bytes they render to.
func owed(root string) ([]Row, []byte, error) {
	rows, err := Derive(root)
	if err != nil {
		return nil, nil, err
	}
	want, err := render(rows)
	if err != nil {
		return nil, nil, err
	}

	return rows, want, nil
}

// verdictOf answers why the table at full has to be rewritten to hold want:
// reasonMissing, reasonStale, or empty when it already holds it. A read that
// fails for any reason but absence is an error, never a verdict.
func verdictOf(full string, want []byte) (string, error) {
	got, err := os.ReadFile(full) //nolint:gosec // a build tool reads the checkout it was pointed at
	if errors.Is(err, os.ErrNotExist) {
		return reasonMissing, nil
	}
	if err != nil {
		return "", err
	}
	if !bytes.Equal(got, want) {
		return reasonStale, nil
	}

	return "", nil
}
