// VALIDATES: ze-doc-wiring-check runs every repository check as a linked Go
// function while preserving the producer's stage order, output, and codes.
// PREVENTS: a missing callback, skipped sub-stage, or unreadable fixture being
// treated as a clean result after the process fallbacks are removed.

package docwiring

import (
	"bytes"
	"context"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/a-h/templ/cmd/templ/generatecmd"
)

func nativeGitTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := tree(t, files)
	for _, args := range [][]string{{"init", "-q"}, {"add", "-A"}} {
		cmd := exec.Command("git", append([]string{"-C", root}, args...)...) //nolint:gosec,noctx // Git is the fixture population under test
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %s: %v: %s", strings.Join(args, " "), err, out)
		}
	}
	return root
}

func TestNativeDesignReferenceFixturePreservesProducerOutputAndCode(t *testing.T) {
	root := nativeGitTree(t, map[string]string{
		"go.mod":                  "module fixture\n\ngo 1.25\n",
		"docs/design.md":          "# Durable design\n",
		"plan/spec-closing.md":    "# Temporary spec\n",
		"internal/x/x.go":         "// Design: docs/design.md -- x\npackage x\n",
		"internal/x/x_test.go":    "// Design: plan/spec-closing.md -- fixture\npackage x\n",
		"internal/x/generated.go": "// Code generated by fixture. DO NOT EDIT.\n// Design: docs/missing.md\npackage x\n",
	})
	g := &gate{root: root}
	result := g.checkDesignRefs()
	want := "internal/x/x_test.go:1: a test must cite a durable document, never a spec deleted at closure " +
		"(ai/rules/planning.md): plan/spec-closing.md\n"
	if !result.Failed || result.Output != want {
		t.Fatalf("design fixture = %+v, want producer output %q and code 1", result, want)
	}

	if err := os.WriteFile(filepath.Join(root, "internal", "x", "x_test.go"),
		[]byte("// Design: docs/design.md -- fixture\npackage x\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	result = g.checkDesignRefs()
	if result.Failed || result.Output != "every path reference resolves\n" {
		t.Errorf("clean design fixture = %+v, want producer success output and code 0", result)
	}
}

