// TestNativeDesignReferenceScanKeepsDeletedAndUnreadableTrackedSourcesApart
// removes one indexed file, then tracks a dangling symlink in the same tree.
//
// VALIDATES: a deleted tracked source is absent work, while an existing path
// that cannot be opened still fails the scan closed.
// PREVENTS: concurrent deletions reddening the gate, or a broad ENOENT skip
// hiding an unreadable tracked path.
func TestNativeDesignReferenceScanKeepsDeletedAndUnreadableTrackedSourcesApart(t *testing.T) {
	root := nativeGitTree(t, map[string]string{
		"go.mod":          "module fixture\n",
		".gitignore":      "docs/generated.md\n",
		"internal/x/x.go": "// Design: docs/generated.md -- generated locally\npackage x\n",
	})
	result := (&gate{root: root}).checkDesignRefs()
	if result.Failed {
		t.Fatalf("an ignored generated target was reported missing: %+v", result)
	}
	if err := os.Remove(filepath.Join(root, "internal", "x", "x.go")); err != nil {
		t.Fatal(err)
	}
	result = (&gate{root: root}).checkDesignRefs()
	if result.Failed {
		t.Fatalf("a deleted tracked source was reported unreadable: %+v", result)
	}

	broken := filepath.Join(root, "internal", "x", "broken.go")
	if err := os.Symlink("absent.go", broken); err != nil {
		t.Skipf("symlink fixture unavailable: %v", err)
	}
	cmd := exec.Command("git", "-C", root, "add", "internal/x/broken.go") //nolint:gosec,noctx // Git is the fixture population under test
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("track unreadable fixture: %v: %s", err, out)
	}
	result = (&gate{root: root}).checkDesignRefs()
	if !result.Failed || result.Code != 2 || !strings.Contains(result.Message, "broken.go") {
		t.Errorf("an unreadable tracked source answered %+v", result)
	}
}

func TestNativeDocIndexAndSpecCitationCallbacksPreserveFixtureVerdicts(t *testing.T) {
	root := tree(t, map[string]string{
		"docs/one.md":             "<!-- source: internal/x/x.go -- X -->\n",
		"internal/x/x.go":         "package x\n\ntype X struct{}\n",
		"plan/spec-one.md":        "See plan/spec-two.md.\n",
		"plan/spec-two.md":        "# Two\n",
		"plan/.citation-baseline": "",
	})
	if payload, code := answerDocIndex(root); code != 0 || !strings.Contains(prose(payload), "all references valid") {
		t.Errorf("clean doc index code=%d output=%q", code, prose(payload))
	}
	if err := os.Remove(filepath.Join(root, "internal", "x", "x.go")); err != nil {
		t.Fatal(err)
	}
	if payload, code := answerDocIndex(root); code != 1 ||
		!strings.Contains(prose(payload), "stale references") {
		t.Errorf("stale doc index code=%d output=%q", code, prose(payload))
	}
	if payload, code := answerSpecCitation(root); code != 0 ||
		!strings.Contains(prose(payload), "spec-citation-check OK") {
		t.Errorf("clean spec citation code=%d output=%q", code, prose(payload))
	}

	if err := os.Remove(filepath.Join(root, "plan", "spec-two.md")); err != nil {
		t.Fatal(err)
	}
	payload, code := answerSpecCitation(root)
	if code != 1 || !strings.Contains(prose(payload), "spec-citation-check FAILED") {
		t.Errorf("dangling spec citation code=%d output=%q", code, prose(payload))
	}
}

func TestNativeTemplCallbackDrivesScopeOrphanAndCompilerStages(t *testing.T) {
	for name, files := range map[string]map[string]string{
		"stray source": {
			"go.mod": "module fixture\n", "outside/page.templ": "package outside\n",
		},
		"orphan output": {
			"go.mod": "module fixture\n", "internal/x/page_templ.go": "package x\n",
		},
	} {
		t.Run(name, func(t *testing.T) {
			root := nativeGitTree(t, files)
			payload, code := answerTemplOutput(root)
			if code != 1 || prose(payload) == "" {
				t.Errorf("templ %s code=%d output=%q", name, code, prose(payload))
			}
		})
	}

	root := nativeGitTree(t, map[string]string{
		"go.mod":                "module fixture\n\ngo 1.25\n",
		"internal/x/page.templ": "package x\n\ntempl Hello() {\n<p>Hello</p>\n}\n",
	})
	var stdout, stderr bytes.Buffer
	if err := generatecmd.Run(context.Background(), &stdout, &stderr,
		[]string{"-path", filepath.Join(root, "internal")}); err != nil {
		t.Fatalf("generate compiler fixture: %v: %s", err, stderr.String())
	}
	if payload, code := answerTemplOutput(root); code != 0 {
		t.Fatalf("fresh templ output code=%d output=%q", code, prose(payload))
	}
	if err := os.WriteFile(filepath.Join(root, "internal", "x", "page.templ"),
		[]byte("package x\n\ntempl Hello() {\n<p>Changed</p>\n}\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if payload, code := answerTemplOutput(root); code != 1 || prose(payload) == "" {
		t.Errorf("stale templ output code=%d output=%q", code, prose(payload))
	}
}

func TestNativeDocVerifyRunsEveryStageAndKeepsTheProducerOrder(t *testing.T) {
	payload, code := answerDocVerify(t.TempDir())
	page := prose(payload)
	if code != 1 {
		t.Fatalf("incomplete fixture code=%d, want aggregate failure", code)
	}
	position := 0
	for _, stage := range docVerifyStages {
		needle := "  -> " + stage.heading
		next := strings.Index(page[position:], needle)
		if next < 0 {
			t.Fatalf("doc verify omitted or reordered %q:\n%s", stage.heading, page)
		}
		position += next + len(needle)
	}
	if !strings.HasSuffix(page, "Documentation tests FAILED -- see output above.\n"+
		"See docs/contributing/documentation-testing.md for how to fix.\n") {
		t.Errorf("aggregate failure footer drifted:\n%s", page)
	}
}
