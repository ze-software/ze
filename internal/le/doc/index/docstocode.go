// Design: docs/architecture/core-design.md -- the generated docs-to-code index
// Detail: report.go -- what the command answers, and the rendering of the file
// Detail: codetodocs.go -- the MIRROR index, from the anchors inside docs/
//
// Package docindex generates ai/DOCS-TO-CODE.md, the reverse index from the
// `// Design:` headers that live in Go files.
//
// Every non-test, non-generated Go file has a
// `// Design: <doc> -- topic` header (ai/rules/go-standards.md, hook-enforced).
// The code-to-docs index inverts `<!-- source: -->` anchors from docs/. This
// index maps each `// Design:` edge in the opposite direction. A reader can
// therefore find all files that implement a design document with no tree search.
package docindex

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	docconsistency "github.com/ze-software/ze/internal/le/doc/consistency"
)

const (
	// OutputRel is the index this tool writes, relative to the checkout.
	OutputRel = "ai/DOCS-TO-CODE.md"

	// StaleExit means that the committed output no longer matches its sources.
	// It differs from 1, which means that the generator failed. The commit gate
	// BLOCKS on drift but stays warn-only when the generator fails. The exit
	// code is the contract, and the warning text CAN change.
	StaleExit = 3

	// InlineRefs is the largest reference list rendered as bullets. Above it
	// the entry becomes a table, because a longer list is read by scanning a
	// column rather than by reading sentences.
	InlineRefs = 3

	// ModCache holds extracted external modules AND a self-copy of ze,
	// regenerated by appliance builds. Indexing those duplicates the working
	// tree and is not first-party source.
	ModCache = "gokrazy/modcache"

	// Cache is the checkout's build cache. Its stdpatch trees link every
	// stdlib file into the GOROOT of whichever machine built them, so a tree
	// another machine built through a shared cache holds links that name
	// nothing here; reading them would fail the walk on machine state, and
	// none of it is first-party source.
	Cache = "cache"
)

// skipPaths are the directories, relative to the checkout root, the walk does
// not enter. They are paths, never names: `cache` is also the name of real
// packages (internal/component/resolve/cache), which skipDirs would drop.
var skipPaths = [...]string{ModCache, Cache}

// skipDirs are directory names the walk does not enter.
var skipDirs = map[string]bool{
	"vendor":       true,
	"tmp":          true,
	"testdata":     true,
	"node_modules": true,
	".git":         true,
}

// Reference is one edge of the index: a design document, the file that cites
// it, and the topic that citation names.
type Reference struct {
	Doc   string `json:"doc"`
	File  string `json:"file"`
	Topic string `json:"topic"`
}

// Build reads the tree and answers every `// Design:` edge in it, sorted by
// document, then file, then topic.
//
// Every read error reaches the caller. If an unreadable file looks like a file
// with no citation, the generator writes that omission into the index. The
// check then agrees with that index and cannot detect the omission. Only a path
// that VANISHED during the walk is not a failure. This checkout is shared, so
// another session can remove a file that was never in the described tree.
func Build(root string) ([]Reference, error) {
	seen := make(map[Reference]bool)
	if err := walkGo(root, root, func(path, rel string) error {
		refs, err := designRefs(path, rel)
		if err != nil {
			return err
		}
		for _, ref := range refs {
			seen[ref] = true
		}
		return nil
	}); err != nil {
		return nil, err
	}

	out := make([]Reference, 0, len(seen))
	for ref := range seen {
		out = append(out, ref)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Doc != out[j].Doc {
			return out[i].Doc < out[j].Doc
		}
		if out[i].File != out[j].File {
			return out[i].File < out[j].File
		}
		return out[i].Topic < out[j].Topic
	})
	return out, nil
}

// walkGo visits every `.go` file under dir, in name order, and hands each one
// its absolute path and its path relative to root.
func walkGo(root, dir string, visit func(path, rel string) error) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if vanished(dir, err) {
			return nil
		}
		return fmt.Errorf("reading %s: %w", dir, err)
	}

	var files, subdirs []string
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() {
			subdirs = append(subdirs, name)
			continue
		}
		if strings.HasSuffix(name, ".go") {
			files = append(files, name)
		}
	}

	slices.Sort(files)
	for _, name := range files {
		path := filepath.Join(dir, name)
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return fmt.Errorf("locating %s under %s: %w", path, root, err)
		}
		if err := visit(path, filepath.ToSlash(rel)); err != nil {
			return err
		}
	}

	slices.Sort(subdirs)
	for _, name := range subdirs {
		sub := filepath.Join(dir, name)
		rel, err := filepath.Rel(root, sub)
		if err != nil {
			return fmt.Errorf("locating %s under %s: %w", sub, root, err)
		}
		if SkipsDir(filepath.ToSlash(rel)) {
			continue
		}
		if err := walkGo(root, sub, visit); err != nil {
			return err
		}
	}
	return nil
}

// designRefs answers every design edge one file's header declares. The header
// rule is docconsistency.DesignHeader, the one every reader of a `// Design:`
// header shares, so a line this index records is a line the doc check, the
// spec citation audit and the edit gate read too.
func designRefs(path, rel string) ([]Reference, error) {
	content, err := os.ReadFile(path) //nolint:gosec // path comes from a walk of the tree the caller named
	if err != nil {
		if vanished(path, err) {
			return nil, nil
		}
		return nil, fmt.Errorf("reading %s: %w", path, err)
	}

	var refs []Reference
	for _, link := range docconsistency.DesignHeader(string(content)) {
		refs = append(refs, Reference{Doc: link.Page, File: rel, Topic: link.Topic})
	}
	return refs, nil
}

// vanished reports a path that disappeared during the walk. This checkout is
// shared, so another session can remove a file between the listing and read.
// That file was not part of the described tree. The generator does not report
// another session's timing as a defect.
func vanished(path string, err error) bool {
	if !errors.Is(err, fs.ErrNotExist) {
		return false
	}
	_, statErr := os.Lstat(path)
	return errors.Is(statErr, fs.ErrNotExist)
}

// SkipsDir reports whether the walk does not enter a directory. rel is the
// directory's path relative to the checkout root, in slash form, and names a
// directory below the root, never the root itself.
//
// It is the one declaration of the source population: walkGo, IsDesignSource
// and every other walk that counts first-party source ask it, so no caller
// keeps a copy of the set that can miss a later addition such as cache/.
func SkipsDir(rel string) bool {
	if slices.Contains(skipPaths[:], rel) {
		return true
	}
	name := path.Base(rel)
	if skipDirs[name] {
		return true
	}
	return strings.HasPrefix(name, ".")
}

// IsDesignSource reports whether writing source can change ai/DOCS-TO-CODE.md.
// source is relative to the checkout root, in slash form.
//
// The index is built from the `// Design:` header of every `.go` file walkGo
// visits, so its inputs are exactly that walk: a `.go` file under a directory
// the walk enters. Each ancestor directory is put to SkipsDir, the question
// walkGo asks, so this predicate and the generator cannot answer two different
// trees.
//
// The header itself is NOT consulted. An edit that REMOVES a `// Design:` line
// changes the index as surely as one that adds one, and this is asked after the
// write, when the removed line is already gone.
func IsDesignSource(source string) bool {
	if !strings.HasSuffix(source, ".go") {
		return false
	}
	// The loop ends at "." for a relative path and at "/" for one that is not,
	// because path.Dir answers each of those for itself.
	for dir := path.Dir(source); dir != "." && dir != "/"; dir = path.Dir(dir) {
		if SkipsDir(dir) {
			return false
		}
	}
	return true
}
