package l2tp

import (
	"errors"
	"net/netip"
	"os"
	"sync"
	"sync/atomic"
	"testing"

	"golang.org/x/sys/unix"
)

var counterTransportSequence atomic.Uint32

// kernelCounterTransport returns a genuine attached PPPoL2TP carrier. The
// caller MUST first enter the test's own network namespace. It MUST register
// channel/unit cleanup after this call so those owners close before transport,
// session, tunnel and UDP sockets. No traffic is generated by this fixture.
// Every native refusal fails the test; unsupported hosts do not silently pass.
func kernelCounterTransport(t *testing.T) *os.File {
	t.Helper()
	transport, _ := kernelCounterTransportWithRelease(t)
	return transport
}

// kernelCounterTransportWithRelease exposes the fixture's same original
// transport close. Explicit producer cleanup and fallback cleanup share one
// cached physical close, including failure; no consumed raw FD is retried.
func kernelCounterTransportWithRelease(t *testing.T) (*os.File, func() error) {
	t.Helper()
	if err := probeKernelModules(); err != nil {
		t.Fatalf("native PPP counter fixture requires L2TP: %v", err)
	}
	genl, err := resolveGenlFamily()
	if err != nil {
		t.Fatal(err)
	}
	listener := kernelCounterUDPSocket(t)
	peer := kernelCounterUDPSocket(t)
	address, err := unix.Getsockname(peer)
	if err != nil {
		t.Fatal(err)
	}
	ipv4, ok := address.(*unix.SockaddrInet4)
	if !ok {
		t.Fatalf("counter transport peer address=%T", address)
	}
	peerAddress := netip.AddrPortFrom(netip.AddrFrom4(ipv4.Addr), uint16(ipv4.Port))
	sequence := counterTransportSequence.Add(1)
	if sequence > 50000 {
		t.Fatal("counter transport fixture exhausted its distinct tunnel labels")
	}
	tunnelID := uint16(10000 + sequence)
	const localSID, remoteSID = uint16(1), uint16(2)
	connection, err := genl.tunnelCreate(tunnelID, tunnelID, listener, peerAddress)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		deleteErr := genl.tunnelDelete(tunnelID)
		closeErr := unix.Close(connection)
		if err := errors.Join(deleteErr, closeErr); err != nil {
			t.Error(err)
		}
	})
	if err := genl.sessionCreate(sessionCreateParams{
		tunnelID: tunnelID,
		localSID: localSID, remoteSID: remoteSID,
	}); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := genl.sessionDelete(tunnelID, localSID); err != nil {
			if !errors.Is(err, unix.ENODEV) {
				t.Error(err)
			}
		}
	})
	transport, err := pppoxCreate(connection, peerAddress, tunnelID, localSID, tunnelID, remoteSID)
	if err != nil {
		t.Fatal(err)
	}
	var closeOnce sync.Once
	var closeErr error
	release := func() error {
		closeOnce.Do(func() { closeErr = transport.Close() })
		return closeErr
	}
	t.Cleanup(func() {
		if err := release(); err != nil {
			t.Error(err)
		}
	})
	return transport, release
}

func kernelCounterUDPSocket(t *testing.T) int {
	t.Helper()
	fd, err := unix.Socket(unix.AF_INET, unix.SOCK_DGRAM|unix.SOCK_CLOEXEC, 0)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := unix.Close(fd); err != nil {
			t.Error(err)
		}
	})
	if err := unix.SetsockoptInt(fd, unix.SOL_SOCKET, unix.SO_REUSEPORT, 1); err != nil {
		t.Fatal(err)
	}
	if err := unix.Bind(fd, &unix.SockaddrInet4{Addr: [4]byte{127, 0, 0, 1}}); err != nil {
		t.Fatal(err)
	}
	return fd
}
