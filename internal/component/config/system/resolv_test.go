// readNameservers answers the nameserver lines of the resolv.conf at path.
func readNameservers(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path) //nolint:gosec // test temp path
	require.NoError(t, err)
	return string(data)
}

// TestResolversWithdrawOneSourceKeepsTheOther: a DHCPv4 and a DHCPv6 lease
// coexist in resolv.conf, and withdrawing one removes only its servers.
//
// VALIDATES: per-source tracking (owner decision 2026-10-18, A-7), the union
// order (DHCPv4 before DHCPv6) and deduplication of a server both leases carry.
// PREVENTS: the last writer replacing every other lease's servers, and a
// lease end leaving its servers in the file.
func TestResolversWithdrawOneSourceKeepsTheOther(t *testing.T) {
	path := filepath.Join(t.TempDir(), "resolv.conf")
	var r system.Resolvers
	require.NoError(t, r.Configure(path, nil))

	v4 := system.DHCPv4ResolverSource("eth0", "0")
	v6 := system.DHCPv6ResolverSource("eth0", "0")
	require.NoError(t, r.SetLease(v6, []string{"2001:db8::53", "192.0.2.53"}))
	require.NoError(t, r.SetLease(v4, []string{"192.0.2.53", "198.51.100.53"}))
	assert.Equal(t, "# Generated by ze\n"+
		"nameserver 192.0.2.53\n"+
		"nameserver 198.51.100.53\n"+
		"nameserver 2001:db8::53\n", readNameservers(t, path))

	require.NoError(t, r.SetLease(v6, nil))
	assert.Equal(t, "# Generated by ze\n"+
		"nameserver 192.0.2.53\n"+
		"nameserver 198.51.100.53\n", readNameservers(t, path))

	require.NoError(t, r.SetLease(v4, nil))
	assert.Equal(t, "# Generated by ze\n", readNameservers(t, path),
		"the last lease withdrawn leaves no ze server behind")
}

// TestResolversStaticWins: configured name-servers are the whole file while
// they exist, and the leases return when they are removed.
//
// VALIDATES: RFC 3646 Section 6 "these parameters SHOULD NOT be overridden by
// DHCP", and a reload that removes the static servers.
// PREVENTS: a DHCP lease overriding the operator's name-servers.
func TestResolversStaticWins(t *testing.T) {
	path := filepath.Join(t.TempDir(), "resolv.conf")
	var r system.Resolvers
	require.NoError(t, r.Configure(path, []string{"9.9.9.9"}))
	require.NoError(t, r.SetLease(system.DHCPv4ResolverSource("eth1", "0"), []string{"192.0.2.53"}))
	assert.Equal(t, "# Generated by ze\nnameserver 9.9.9.9\n", readNameservers(t, path))

	require.NoError(t, r.Configure(path, nil))
	assert.Equal(t, "# Generated by ze\nnameserver 192.0.2.53\n", readNameservers(t, path))
}

// TestResolversLeaseOrderIsStable: leases render by protocol, then interface,
// whatever order they arrived in.
//
// VALIDATES: the deterministic order documented on Resolvers.
// PREVENTS: a file whose order depends on map iteration or arrival.
func TestResolversLeaseOrderIsStable(t *testing.T) {
	var r system.Resolvers
	require.NoError(t, r.SetLease(system.DHCPv6ResolverSource("eth0", "0"), []string{"2001:db8::1"}))
	require.NoError(t, r.SetLease(system.DHCPv4ResolverSource("eth9", "0"), []string{"192.0.2.9"}))
	require.NoError(t, r.SetLease(system.DHCPv4ResolverSource("eth1", "0"), []string{"192.0.2.1"}))
	assert.Equal(t, []string{"192.0.2.1", "192.0.2.9", "2001:db8::1"}, r.Servers())
}

// TestResolversNeverEmptyAForeignFile: with no server ever written, an empty
// set leaves an existing resolv.conf alone; an empty path writes nothing.
//
// VALIDATES: the written guard on Resolvers.
// PREVENTS: ze replacing a resolv.conf it never managed with an empty one.
func TestResolversNeverEmptyAForeignFile(t *testing.T) {
	path := filepath.Join(t.TempDir(), "resolv.conf")
	require.NoError(t, os.WriteFile(path, []byte("nameserver 10.0.0.1\n"), 0o600))
	var r system.Resolvers
	require.NoError(t, r.Configure(path, nil))
	require.NoError(t, r.SetLease(system.DHCPv4ResolverSource("eth0", "0"), nil))
	assert.Equal(t, "nameserver 10.0.0.1\n", readNameservers(t, path))

	var disabled system.Resolvers
	require.NoError(t, disabled.Configure("", []string{"8.8.8.8"}))
	assert.Equal(t, []string{"8.8.8.8"}, disabled.Servers())
}

// TestResolversRefuseUnnamedSource: the zero source is refused.
//
// VALIDATES: SetLease names every source it records.
// PREVENTS: servers no lease can withdraw.
func TestResolversRefuseUnnamedSource(t *testing.T) {
	var r system.Resolvers
	require.Error(t, r.SetLease(system.ResolverSource{}, []string{"192.0.2.1"}))
}
