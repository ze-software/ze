func TestManagedStartupCLIFilesRefuseMissingDirectoryAndUnreadable(t *testing.T) {
	settings := defaultTestSettings()
	settings.StartupCLIFile = filepath.Join(t.TempDir(), "missing.cli")
	if err := checkManagedStartupCLI(settings, openStartupCLIFile); !errors.Is(err, os.ErrNotExist) || !strings.Contains(err.Error(), settings.StartupCLIFile) {
		t.Fatal("missing original file lost path/cause", err)
	}
	if err := os.WriteFile(settings.StartupCLIFile, nil, 0o600); err != nil {
		t.Fatal(err)
	}
	if err := checkManagedStartupCLI(settings, openStartupCLIFile); err != nil {
		t.Fatal("empty actual regular CLI file was refused", err)
	}
	settings.StartupCLIFile = t.TempDir()
	if err := checkManagedStartupCLI(settings, openStartupCLIFile); err == nil {
		t.Fatal("directory accepted as VPP command file")
	}
	settings.StartupCLIFile = "/evidence/unreadable.cli"
	if err := checkManagedStartupCLI(settings, func(string) (startupCLIFile, error) { return nil, os.ErrPermission }); !errors.Is(err, os.ErrPermission) {
		t.Fatal("unreadable original cause was hidden", err)
	}
	settings.External = true
	calls := 0
	if err := checkManagedStartupCLI(settings, func(string) (startupCLIFile, error) { calls++; return nil, os.ErrPermission }); err != nil || calls != 0 {
		t.Fatal("external supervisor file was inspected", err, calls)
	}
	settings.External = false
	settings.StartupCLIFile = ""
	if err := checkManagedStartupCLI(settings, func(string) (startupCLIFile, error) { calls++; return nil, os.ErrPermission }); err != nil || calls != 0 {
		t.Fatal("absent optional file changed existing behavior", err, calls)
	}
}

type managedStartupReadFault struct {
	*os.File
	readError, closeError error
	closed                int
}

func (file *managedStartupReadFault) Read([]byte) (int, error) { return 0, file.readError }
func (file *managedStartupReadFault) Close() error {
	file.closed++
	return errors.Join(file.File.Close(), file.closeError)
}

func TestManagedStartupCLIReadFailureClosesOriginalFile(t *testing.T) {
	path := filepath.Join(t.TempDir(), "commands.cli")
	if err := os.WriteFile(path, []byte("show version\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	actual, err := os.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = actual.Close() }() // fallback runs after the immediate original-Close oracle
	readFailure, closeFailure := errors.New("original read refused"), errors.New("original close refused")
	file := &managedStartupReadFault{File: actual, readError: readFailure, closeError: closeFailure}
	settings := defaultTestSettings()
	settings.StartupCLIFile = path
	err = checkManagedStartupCLI(settings, func(string) (startupCLIFile, error) { return file, nil })
	if !errors.Is(err, readFailure) || !errors.Is(err, closeFailure) || file.closed != 1 {
		t.Fatal("file validation lost original errors or original Close", err, file.closed)
	}
	fileInfo, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if !fileInfo.Mode().IsRegular() {
		t.Fatal("control is not an actual regular file")
	}
}

