func managedStartupTree(t *testing.T, values map[string]any) *config.Tree {
	t.Helper()
	tree, err := config.TreeFromPluginMap(map[string]any{"vpp": values})
	if err != nil {
		t.Fatal(err)
	}
	return tree
}
func managedStartupSections(t *testing.T, tree *config.Tree) []sdk.ConfigSection {
	t.Helper()
	data, err := json.Marshal(map[string]any{"vpp": tree.GetContainer("vpp").ToPluginMap()})
	if err != nil {
		t.Fatal(err)
	}
	return []sdk.ConfigSection{{Root: "vpp", Data: string(data)}}
}
func managedStartupSettings(t *testing.T, values map[string]any) *VPPSettings {
	t.Helper()
	settings, err := ParseConfigSections(managedStartupSections(t, managedStartupTree(t, values)))
	if err != nil {
		t.Fatal(err)
	}
	return settings
}

func TestManagedStartupDeliveredTreeSelectsExplicitControls(t *testing.T) {
	path := filepath.Join(t.TempDir(), "bootstrap.cli")
	if err := os.WriteFile(path, []byte("show version\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	settings := managedStartupSettings(t, map[string]any{"enabled": "true", "startup-cli-file": path,
		"plugins": map[string]any{"dpdk": "false", "af-packet": "true"}, "memory": map[string]any{"hugepage-size": "default"}})
	if err := settings.Validate(); err != nil {
		t.Fatal(err)
	}
	if settings.StartupCLIFile != path {
		t.Fatal("delivered tree lost original CLI path")
	}
	out := generateToString(t, settings)
	if strings.Contains(out, "plugin dpdk_plugin.so") {
		t.Fatal("explicit DPDK false still loads DPDK")
	}
	for _, want := range []string{"plugin af_packet_plugin.so {\n    enable\n  }", "plugin urpf_plugin.so {\n    enable\n  }"} {
		if !strings.Contains(out, want) {
			t.Fatal("explicit product control did not reach native generator", want, out)
		}
	}
	if strings.Contains(out, "  exec ") {
		t.Fatal("manager-owned bootstrap leaked an asynchronous native directive", out)
	}
	if strings.Count(out, "  page-size default\n") != 2 {
		t.Fatal("explicit base-page choice did not reach both native sections", out)
	}
	if err := checkManagedStartupCLI(settings, openStartupCLIFile); err != nil {
		t.Fatal("actual readable bootstrap refused", err)
	}
}

func TestManagedStartupDefaultsAndExplicitHugepagesPreserveOutput(t *testing.T) {
	settings := managedStartupSettings(t, map[string]any{"enabled": "true"})
	baseline := generateToString(t, settings)
	// Exact existing renderer output. This is an output byte contract, not a
	// configuration reader guessing operator intent from textual matches.
	want := "unix {\n  nodaemon\n  cli-listen /run/vpp/cli.sock\n  log " + vppLogPath + "\n  full-coredump\n}\n\napi-segment {\n  prefix vpp\n}\n\nsocksvr {\n  socket-name /run/vpp/api.sock\n}\n\ncpu {\n}\n\nbuffers {\n  buffers-per-numa 128000\n  default data-size 2048\n  page-size default-hugepage\n}\n\nplugins {\n  plugin default {\n    disable\n  }\n  plugin dpdk_plugin.so {\n    enable\n  }\n  plugin urpf_plugin.so {\n    enable\n  }\n  plugin linux_cp_plugin.so {\n    enable\n  }\n  plugin linux_nl_plugin.so {\n    enable\n  }\n}\n\nlinux-cp {\n  lcp-sync\n  lcp-auto-subint\n  default netns dataplane\n}\n\nlinux-nl {\n  nl-rx-buffer-size 67108864\n}\n\nmemory {\n  main-heap-size 1G\n}\n\nstatseg {\n  size 512M\n  page-size default-hugepage\n  socket-name /run/vpp/stats.sock\n}\n\n"
	if baseline != want {
		t.Fatal("omitted controls changed existing generated bytes", baseline)
	}
	for _, page := range []string{"2M", "1G"} {
		explicit := managedStartupSettings(t, map[string]any{"enabled": "true", "memory": map[string]any{"hugepage-size": page}})
		expected := baseline
		if page == "1G" {
			expected = strings.ReplaceAll(expected, "page-size default-hugepage", "page-size 1G")
		}
		if out := generateToString(t, explicit); out != expected {
			t.Fatal("explicit existing hugepage choice changed unrelated native bytes", page, out)
		}
	}
}

func TestManagedStartupRejectsDPDKConflictBeforeRendering(t *testing.T) {
	settings := managedStartupSettings(t, map[string]any{"enabled": "true", "plugins": map[string]any{"dpdk": "false"}})
	settings.DPDK.Interfaces = []DPDKInterface{{PCIAddress: "0000:03:00.0", Name: "xe0"}}
	if err := settings.Validate(); err == nil || !strings.Contains(err.Error(), "dpdk") {
		t.Fatal("disabled plugin accepted configured native NIC", err)
	}
	var out bytes.Buffer
	if err := GenerateStartupConf(&out, settings, testHostInventory()); err == nil || out.Len() != 0 {
		t.Fatal("conflicting raw settings published partial native configuration", err, out.String())
	}
	enabled := true
	settings.Plugins.DPDK = &enabled
	if err := settings.Validate(); err != nil {
		t.Fatal(err)
	}
	if out := generateToString(t, settings); !strings.Contains(out, "dev 0000:03:00.0") || !strings.Contains(out, "plugin dpdk_plugin.so") {
		t.Fatal("explicit DPDK positive control no longer programs configured NIC", out)
	}
}

func TestManagedStartupStrictNewControlsRefuseInvalidInputs(t *testing.T) {
	for _, input := range []string{
		`{"enabled":"true","plugins":{"dpdk":"yes"}}`,
		`{"enabled":"true","plugins":{"af-packet":"1"}}`,
		`{"enabled":"true","plugins":{"dpdk":false}}`,
		`{"enabled":"true","plugins":{"af-packet":null}}`,
		`{"enabled":"true","plugins":{"af-pakcet":"true"}}`,
		`{"enabled":"true","memory":{"hugepage-size":"4K"}}`,
		`{"enabled":"true","startup-cli-file":[]}`,
		`{"enabled":"false","startup-cli-file":"/tmp/a\nmore"}`,
	} {
		if settings, err := ParseSettings(json.RawMessage(input)); err == nil || settings != nil {
			t.Fatal("invalid raw control accepted", input, err)
		}
	}
	if _, err := ParseSettings(json.RawMessage(`{"plugins":{"af-pakcet":"true"}}`)); err == nil || !strings.Contains(err.Error(), "af-packet") {
		t.Fatal("unknown new key lost its closest valid spelling", err)
	}
	raw := defaultTestSettings()
	raw.Memory.HugepageSize = "4K"
	var out bytes.Buffer
	if err := raw.Validate(); err == nil {
		t.Fatal("invalid raw page choice bypassed candidate validation")
	}
	if err := GenerateStartupConf(&out, raw, testHostInventory()); err == nil || out.Len() != 0 {
		t.Fatal("invalid raw page mode silently rendered a fallback", err, out.String())
	}
}

