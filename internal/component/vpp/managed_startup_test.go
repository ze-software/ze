// TestManagedStartupRunRefusesMissingFileBeforeSideEffects calls the initial
// lifecycle entry with a real missing original file and a configured NIC.
// The existing loader seam records and refuses every binding attempt before
// it can touch the host; generated output must also remain unchanged.
func TestManagedStartupRunRefusesMissingFileBeforeSideEffects(t *testing.T) {
	for _, existing := range []bool{false, true} {
		name := "absent-output-directories"
		if existing {
			name = "existing-generated-file"
		}
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			confRoot := filepath.Join(root, "generated")
			confDir := filepath.Join(confRoot, "nested")
			confPath := filepath.Join(confDir, "startup.conf")
			originalBytes := []byte("existing generated-file sentinel\n")
			if existing {
				if err := os.MkdirAll(confDir, 0o750); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(confPath, originalBytes, 0o600); err != nil {
					t.Fatal(err)
				}
			}
			settings := defaultTestSettings()
			settings.StartupCLIFile = filepath.Join(root, "missing.cli")
			settings.DPDK.Interfaces = []DPDKInterface{{PCIAddress: "0000:03:00.0", Name: "xe0"}}
			manager := NewVPPManager(settings, confDir, filepath.Join(root, "binary-must-not-be-executed"))
			originalLoader := loadModule
			bindingRefused := errors.New("test refuses real DPDK module loading")
			bindingCalls := 0
			loadModule = func(string) error {
				bindingCalls++
				return bindingRefused
			}
			t.Cleanup(func() { loadModule = originalLoader })
			// Positive control: the same original binder and NIC reach the
			// recording refusal before Run's absence oracle is evaluated.
			if err := manager.dpdk.BindAll(settings.DPDK.Interfaces); !errors.Is(err, bindingRefused) {
				t.Fatal("DPDK binding positive control did not reach recording refusal", err)
			}
			if bindingCalls != 1 {
				t.Fatal("DPDK binding positive control has unexpected loader calls", bindingCalls)
			}
			bindingCalls = 0
			err := manager.Run(t.Context())
			original, found := errors.AsType[*os.PathError](err)
			if !found {
				t.Error("initial Run did not refuse the missing original CLI file", err)
			} else if original.Path != settings.StartupCLIFile {
				t.Error("initial Run refused a different path before the original CLI file", original.Path)
			}
			if bindingCalls != 0 {
				t.Error("initial Run attempted DPDK binding before missing-file refusal", bindingCalls)
			}
			if !existing {
				if _, err := os.Lstat(confRoot); !errors.Is(err, os.ErrNotExist) {
					t.Error("initial Run created generated directories before missing-file refusal", err)
				}
				return
			}
			actual, err := os.ReadFile(confPath)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(actual, originalBytes) {
				t.Error("initial Run changed existing generated bytes before missing-file refusal", string(actual))
			}
			entries, err := os.ReadDir(confDir)
			if err != nil {
				t.Fatal(err)
			}
			if len(entries) != 1 {
				t.Fatal("initial Run changed generated directory contents before missing-file refusal", entries)
			}
			if entries[0].Name() != "startup.conf" {
				t.Error("initial Run replaced the generated directory entry before missing-file refusal", entries[0].Name())
			}
		})
	}
}

func TestManagedStartupCLIDoctorRegisteredAndFixesOriginalPath(t *testing.T) {
	path := filepath.Join(t.TempDir(), "missing.cli")
	tree := managedStartupTree(t, map[string]any{"enabled": "true", "startup-cli-file": path})
	var found *diagnostic.DoctorCheck
	for _, candidate := range diagnostic.DoctorChecksForPhase(diagnostic.DoctorPhasePostConfig) {
		if candidate.Name == "vpp-startup-cli-file" {
			copy := candidate
			found = &copy
			break
		}
	}
	if found == nil {
		t.Fatal("actual doctor registry has no managed startup file check")
	}
	for _, values := range []map[string]any{
		{"enabled": "true", "memory": map[string]any{"hugepage-size": "1G"}},
		{"enabled": "false", "startup-cli-file": path},
		{"enabled": "true", "external": "true", "startup-cli-file": path},
	} {
		if diags := found.Check(diagnostic.DoctorCheckContext{Tree: managedStartupTree(t, values)}); len(diags) != 0 {
			t.Fatal("startup file doctor claimed unrelated or externally owned configuration", diags)
		}
	}
	diags := found.Check(diagnostic.DoctorCheckContext{Tree: tree})
	if len(diags) != 1 || diags[0].Code != doctorVPPStartupCLIFileCode || diags[0].Fix == "" || !strings.Contains(diags[0].Message, path) {
		t.Fatal("registered doctor lost original path/actionable refusal", diags)
	}
	if diagnostic.Lookup(doctorVPPStartupCLIFileCode) == nil {
		t.Fatal("doctor code has no registered operator explanation")
	}
	invalid := managedStartupTree(t, map[string]any{"enabled": "true", "startup-cli-file": "relative.cli"})
	if rows := found.Check(diagnostic.DoctorCheckContext{Tree: invalid}); len(rows) != 1 || rows[0].Fix != startupCLIPathFix {
		t.Fatal("doctor suggested creating a file with an invalid native token", rows)
	}
	if err := os.WriteFile(path, []byte("show version\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if diags := found.Check(diagnostic.DoctorCheckContext{Tree: tree}); len(diags) != 0 {
		t.Fatal("repaired actual original file did not clear doctor", diags)
	}
}
