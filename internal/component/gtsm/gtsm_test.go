// Design: rfc/short/rfc5082.md -- GTSM, the TTL 255 rule for related ICMP messages
// Overview: gtsm.go -- SetPeers and the table it builds
//
// These tests read what this package asks the kernel for, through the two
// seams SetPeers writes through, so they run on any platform and touch no
// kernel. The proofs that the kernel then behaves as RFC 5082 requires are the
// tagged tests in rfc5082_gtsm_linux_test.go.

package gtsm

import (
	"errors"
	"net/netip"
	"reflect"
	"testing"

	"github.com/ze-software/ze/internal/component/firewall"
)

// captureSeams redirects both kernel writers into the returned recorder and
// resets the package's reconcile state, so each test starts from "nothing is
// installed" whatever ran before it.
type capture struct {
	tables       [][]firewall.Table
	routesWanted [][]Peer
	routesGone   [][]Peer
}

func captureSeams(t *testing.T) *capture {
	t.Helper()

	c := &capture{}
	routes, publish, previous, wasPublished, wasMissing := applyRoutes, publishFilter, current, published, routeMissing

	applyRoutes = func(wanted, gone []Peer) error {
		c.routesWanted = append(c.routesWanted, wanted)
		c.routesGone = append(c.routesGone, gone)
		return nil
	}
	publishFilter = func(tables []firewall.Table) error {
		c.tables = append(c.tables, tables)
		return nil
	}
	previousRanges := currentRanges
	current = nil
	currentRanges = nil
	published = false
	routeMissing = false

	t.Cleanup(func() {
		applyRoutes, publishFilter, current, published, routeMissing = routes, publish, previous, wasPublished, wasMissing
		currentRanges = previousRanges
	})
	return c
}

func gtsmPeer() Peer {
	return Peer{
		Addr:     netip.MustParseAddr("192.0.2.1"),
		Port:     179,
		HopLimit: 255,
		Floor:    255,
	}
}

// TestGTSMPublishesTheICMPFilterTableForAPeer drives the entry point the BGP
// reactor calls and reads the table that reaches the firewall component.
//
// It is the wiring proof for the filter half: a peer set in, one ze_gtsm table
// out, carrying the terms that name that peer.
func TestGTSMPublishesTheICMPFilterTableForAPeer(t *testing.T) {
	c := captureSeams(t)

	if err := SetPeers([]Peer{gtsmPeer()}, nil); err != nil {
		t.Fatalf("SetPeers: %v", err)
	}

	if len(c.tables) != 1 {
		t.Fatalf("published %d times, want 1", len(c.tables))
	}
	tables := c.tables[0]
	if len(tables) != 1 {
		t.Fatalf("published %d tables, want 1", len(tables))
	}
	if tables[0].Name != filterTableName {
		t.Errorf("table name = %q, want %q", tables[0].Name, filterTableName)
	}
	if tables[0].Family != firewall.FamilyInet {
		t.Errorf("table family = %v, want inet", tables[0].Family)
	}
	if len(tables[0].Chains) != 1 {
		t.Fatalf("table carries %d chains, want 1", len(tables[0].Chains))
	}

	chain := tables[0].Chains[0]
	if !chain.IsBase || chain.Hook != firewall.HookInput {
		t.Errorf("chain is base %v at hook %v, want a base chain at the input hook", chain.IsBase, chain.Hook)
	}
	if chain.Policy != firewall.PolicyAccept {
		t.Errorf("chain policy = %v, want accept: this table decides only what it names", chain.Policy)
	}

	icmpTerms := len(relatedICMPTypes) * len(quotedPortSides)
	if len(chain.Terms) != 1+icmpTerms {
		t.Fatalf("chain carries %d terms, want %d (the listen-port term, then one per related ICMP type per quoted port side)", len(chain.Terms), 1+icmpTerms)
	}

	// The listen-port term is found by its name, and only one may carry it.
	// It is the one term that reads the outer source: a SYN's source IS the
	// peer, which is what classifies it Dangerous (RFC 5082 Section 3).
	peer := gtsmPeer()
	listenName := listenTermName(netip.PrefixFrom(peer.Addr, 32))
	var listenTerms int
	var others []firewall.Term
	for _, term := range chain.Terms {
		if term.Name == listenName {
			listenTerms++
			assertListenDrop(t, term, netip.MustParsePrefix("192.0.2.1/32"), 179, firewall.MatchIPv4TTLBelow{Floor: 255})
			continue
		}
		others = append(others, term)
	}
	if listenTerms != 1 {
		t.Errorf("chain carries %d terms named %q, want exactly one listen-port term", listenTerms, listenName)
	}
	if len(others) != icmpTerms {
		t.Fatalf("chain carries %d terms beside the listen-port term, want %d ICMP terms", len(others), icmpTerms)
	}

	// AC-1: every ICMP term claims the error by the destination QUOTED inside
	// it, which is the peer, and no ICMP term reads the outer source. An ICMP
	// error is generated by whichever router met the problem, so the outer
	// source identifies nothing about the session.
	for _, term := range others {
		var quotedDestination, icmpType bool
		for _, m := range term.Matches {
			switch v := m.(type) {
			case firewall.MatchICMPType:
				icmpType = true
			case firewall.MatchICMPErrorQuotedDestination:
				quotedDestination = v.Addr == peer.Addr
			case firewall.MatchSourceAddress:
				t.Errorf("term %q reads the outer source %v; the error's sender is not the session", term.Name, v.Prefix)
			}
		}
		if !icmpType {
			t.Errorf("term %q names no ICMP type, so it is no related-ICMP term", term.Name)
		}
		if !quotedDestination {
			t.Errorf("term %q does not require the quoted destination to be the peer %v", term.Name, peer.Addr)
		}
	}
}

// TestGTSMEveryDropTermRequiresTheQuotedBGPPort is the RFC5082-3-4 guard on
// the terms this package builds. An ICMP error that quotes no TCP header on
// the peer's BGP port belongs to no GTSM session, so no term may be able to
// match it.
func TestGTSMEveryDropTermRequiresTheQuotedBGPPort(t *testing.T) {
	peer := gtsmPeer()
	// The listen-port term is excluded by its name alone: it guards the SYN,
	// which quotes nothing, and assertListenDrop judges its shape. Every other
	// term the peer gets is an ICMP term and keeps every requirement below.
	listenName := listenTermName(netip.PrefixFrom(peer.Addr, 32))
	var terms []firewall.Term
	for _, term := range peerTerms(peer) {
		if term.Name == listenName {
			continue
		}
		terms = append(terms, term)
	}
	if want := len(relatedICMPTypes) * len(quotedPortSides); len(terms) != want {
		t.Fatalf("peerTerms built %d terms beside the listen-port term, want %d", len(terms), want)
	}

	for _, term := range terms {
		var quoted, ttl, destination, icmpType bool
		for _, m := range term.Matches {
			switch v := m.(type) {
			case firewall.MatchICMPErrorQuotedTCPPort:
				quoted = v.Port == peer.Port && v.Side != firewall.QuotedPortUnspecified
			case firewall.MatchIPv4TTLBelow:
				ttl = v.Floor == peer.Floor
			case firewall.MatchICMPErrorQuotedDestination:
				destination = v.Addr == peer.Addr
			case firewall.MatchICMPType:
				icmpType = true
			}
		}
		if !quoted {
			t.Errorf("term %q does not require a quoted TCP header on port %d", term.Name, peer.Port)
		}
		if !ttl {
			t.Errorf("term %q does not require a TTL below the peer's floor %d", term.Name, peer.Floor)
		}
		if !destination {
			t.Errorf("term %q does not require the quoted destination to be the peer", term.Name)
		}
		if !icmpType {
			t.Errorf("term %q names no ICMP type, so it would read a payload as a quoted header", term.Name)
		}
		if len(term.Actions) != 1 {
			t.Fatalf("term %q carries %d actions, want one drop", term.Name, len(term.Actions))
		}
		if _, ok := term.Actions[0].(firewall.Drop); !ok {
			t.Errorf("term %q does not drop", term.Name)
		}
	}
}

// TestGTSMTermsAndRoutesAreValidForTheFirewallComponent runs the published
// table through the firewall component's own validation, which is what
// RegisterTables applies. A term this package builds that the component
// refuses would reach the kernel as nothing at all.
func TestGTSMTermsAreAcceptedByTheFirewallValidator(t *testing.T) {
	tables := FilterTables([]Peer{gtsmPeer()}, []Range{{Prefix: netip.MustParsePrefix("2001:db8:1::/48"), Port: 179, Floor: 255}})
	if len(tables) != 1 {
		t.Fatalf("built %d tables, want 1", len(tables))
	}
	if err := firewall.ValidateTables(tables); err != nil {
		t.Fatalf("the firewall component refuses the table this package builds: %v", err)
	}
}

// TestGTSMWithdrawsEverythingWhenNoPeerEnablesIt is the other half of the
// wiring: the peer set is the whole truth, so a reconcile that names no peer
// withdraws the table and the route rather than leaving either standing.
func TestGTSMWithdrawsEverythingWhenNoPeerEnablesIt(t *testing.T) {
	c := captureSeams(t)

	peer := gtsmPeer()
	if err := SetPeers([]Peer{peer}, nil); err != nil {
		t.Fatalf("SetPeers: %v", err)
	}
	if err := SetPeers(nil, nil); err != nil {
		t.Fatalf("SetPeers withdraw: %v", err)
	}

	if len(c.tables) != 2 {
		t.Fatalf("published %d times, want 2", len(c.tables))
	}
	if c.tables[1] != nil {
		t.Errorf("withdraw published %d tables, want none", len(c.tables[1]))
	}
	if len(c.routesGone) != 2 || len(c.routesGone[1]) != 1 || c.routesGone[1][0].Addr != peer.Addr {
		t.Errorf("withdraw did not hand the peer's route back for removal: %v", c.routesGone)
	}
}

// TestGTSMRetriesARouteTheKernelRefused is the promise the daemon's warning
// and the doctor check make: a peer whose route the kernel refused at config
// apply, because its interface was not up yet, gets the route on the next
// reconcile even though that reconcile names the same peers. The filter is
// published either way, and once the route is in, an unchanged set is left
// alone again.
func TestGTSMRetriesARouteTheKernelRefused(t *testing.T) {
	c := captureSeams(t)
	refusals := 1
	applyRoutes = func(wanted, gone []Peer) error {
		c.routesWanted = append(c.routesWanted, wanted)
		if refusals > 0 {
			refusals--
			return errors.New("replace host route: network is unreachable")
		}
		return nil
	}

	peers := []Peer{gtsmPeer()}
	if err := SetPeers(peers, nil); err == nil {
		t.Fatal("SetPeers reported no error for a route the kernel refused")
	}
	if len(c.tables) != 1 {
		t.Fatalf("the filter was published %d times after the refused route, want 1: the receive half must not wait on the transmit half", len(c.tables))
	}

	if err := SetPeers(peers, nil); err != nil {
		t.Fatalf("SetPeers retry: %v", err)
	}
	if len(c.routesWanted) != 2 {
		t.Fatalf("the route was applied %d times, want 2: the same peer set must retry a missing route", len(c.routesWanted))
	}

	if err := SetPeers(peers, nil); err != nil {
		t.Fatalf("SetPeers unchanged: %v", err)
	}
	if len(c.routesWanted) != 2 {
		t.Errorf("the route was applied %d times, want 2: an unchanged set with every route installed is left alone", len(c.routesWanted))
	}
}

// TestGTSMPublishesNothingWhenItHasNothingToSay proves a deployment that
// configures no GTSM peer never reaches the firewall component at all, so the
// nftables backend is not loaded on a box the operator asked nothing of.
func TestGTSMPublishesNothingWhenItHasNothingToSay(t *testing.T) {
	c := captureSeams(t)

	if err := SetPeers(nil, nil); err != nil {
		t.Fatalf("SetPeers: %v", err)
	}

	if len(c.tables) != 0 || len(c.routesWanted) != 0 {
		t.Errorf("an empty peer set reached the kernel: %d publishes, %d route applies", len(c.tables), len(c.routesWanted))
	}
}

// TestGTSMBuildsNoFilterTermsWithoutAFloor covers the boundary of the receive
// half. A peer configured for the transmit half alone has no floor to compare
// against, and a term built from a zero floor would be a rule that never
// fires and a claim the firewall validator refuses.
func TestGTSMBuildsNoFilterTermsWithoutAFloor(t *testing.T) {
	peer := gtsmPeer()
	peer.Floor = 0

	if terms := peerTerms(peer); terms != nil {
		t.Errorf("built %d terms for a peer with no TTL floor, want none", len(terms))
	}
	if tables := FilterTables([]Peer{peer}, nil); tables != nil {
		t.Errorf("built a table with no terms in it: %v", tables)
	}
}

// TestPeerTermsSkipsUnsetFloorOrPort is A-5: a peer or a range with a zero
// floor or a zero port carries no listen-port term, in either family, because
// such a term would match nothing.
func TestPeerTermsSkipsUnsetFloorOrPort(t *testing.T) {
	for _, addr := range []string{"192.0.2.1", "2001:db8::1"} {
		noFloor := Peer{Addr: netip.MustParseAddr(addr), Port: 179, HopLimit: 255}
		noPort := Peer{Addr: netip.MustParseAddr(addr), HopLimit: 255, Floor: 255}
		if terms := peerTerms(noFloor); terms != nil {
			t.Errorf("%s: built %d terms with no floor, want none", addr, len(terms))
		}
		if terms := peerTerms(noPort); terms != nil {
			t.Errorf("%s: built %d terms with no port, want none", addr, len(terms))
		}
	}
	ranges := []Range{
		{Prefix: netip.MustParsePrefix("10.0.0.0/8"), Port: 179},
		{Prefix: netip.MustParsePrefix("10.0.0.0/8"), Floor: 255},
	}
	if tables := FilterTables(nil, ranges); tables != nil {
		t.Errorf("built a table for ranges with no floor or port: %v", tables)
	}
}

// TestGTSMBuildsNoICMPTermsForAnIPv6Peer records which half of the receive
// rule this package owns for related messages. The IPv6 half is performed by
// the kernel against the IPV6_MINHOPCOUNT that network.SetIPMinTTL installs,
// so an ICMP rule here would be a second answer to a question already
// answered. The peer's one term is its listen-port term.
func TestGTSMBuildsNoICMPTermsForAnIPv6Peer(t *testing.T) {
	peer := Peer{Addr: netip.MustParseAddr("2001:db8::1"), Port: 179, HopLimit: 255, Floor: 255}

	terms := peerTerms(peer)
	if len(terms) != 1 {
		t.Fatalf("built %d terms for an IPv6 peer, want the listen-port term only", len(terms))
	}
	for _, m := range terms[0].Matches {
		if _, icmp := m.(firewall.MatchICMPType); icmp {
			t.Errorf("the IPv6 peer's term carries an ICMP match: %+v", terms[0])
		}
	}
}

// listenDrop is the shape a listen-port term must have: the source, TCP, the
// one destination port, the family's below-floor match, and a drop alone.
func assertListenDrop(t *testing.T, term firewall.Term, source netip.Prefix, port uint16, floor firewall.Match) {
	t.Helper()
	want := []firewall.Match{
		firewall.MatchSourceAddress{Prefix: source},
		firewall.MatchProtocol{Protocol: "tcp"},
		firewall.MatchDestinationPort{Ranges: []firewall.PortRange{{Lo: port, Hi: port}}},
		floor,
	}
	if !reflect.DeepEqual(term.Matches, want) {
		t.Errorf("term %q matches = %+v, want %+v", term.Name, term.Matches, want)
	}
	if !reflect.DeepEqual(term.Actions, []firewall.Action{firewall.Drop{}}) {
		t.Errorf("term %q actions = %+v, want a drop alone", term.Name, term.Actions)
	}
}

// TestPeerTermsListenPortIPv4 is AC-1 and AC-5 at table level: an IPv4 peer's
// first term drops TCP from the peer to its listen port below its own floor,
// 253 for `ttl max 3`, so TTL 253 passes and 252 is dropped.
func TestPeerTermsListenPortIPv4(t *testing.T) {
	peer := Peer{Addr: netip.MustParseAddr("192.0.2.1"), Port: 1179, HopLimit: 255, Floor: 253}
	terms := peerTerms(peer)
	if len(terms) != 1+len(relatedICMPTypes)*len(quotedPortSides) {
		t.Fatalf("built %d terms, want the listen-port term and the ICMP terms", len(terms))
	}
	assertListenDrop(t, terms[0], netip.MustParsePrefix("192.0.2.1/32"), 1179, firewall.MatchIPv4TTLBelow{Floor: 253})
}

// TestPeerTermsListenPortIPv6 is AC-2: the IPv6 peer's term uses the hop-limit
// match, never the IPv4 TTL read.
func TestPeerTermsListenPortIPv6(t *testing.T) {
	peer := Peer{Addr: netip.MustParseAddr("2001:db8::1"), Port: 179, HopLimit: 255, Floor: 255}
	terms := peerTerms(peer)
	if len(terms) != 1 {
		t.Fatalf("built %d terms, want 1", len(terms))
	}
	assertListenDrop(t, terms[0], netip.MustParsePrefix("2001:db8::1/128"), 179, firewall.MatchIPv6HopLimitBelow{Floor: 255})
}

// TestListenTermsDynamicRange is AC-16 at the gtsm boundary: a GTSM dynamic
// group's range yields a listen-port term whose source is the range, with the
// group's floor, in each family.
func TestListenTermsDynamicRange(t *testing.T) {
	ranges := []Range{
		{Prefix: netip.MustParsePrefix("10.1.0.0/16"), Port: 179, Floor: 255},
		{Prefix: netip.MustParsePrefix("2001:db8:5::/48"), Port: 179, Floor: 254},
	}
	tables := FilterTables(nil, ranges)
	if len(tables) != 1 || len(tables[0].Chains[0].Terms) != 2 {
		t.Fatalf("tables = %+v, want one table with one term per range", tables)
	}
	terms := tables[0].Chains[0].Terms
	assertListenDrop(t, terms[0], ranges[0].Prefix, 179, firewall.MatchIPv4TTLBelow{Floor: 255})
	assertListenDrop(t, terms[1], ranges[1].Prefix, 179, firewall.MatchIPv6HopLimitBelow{Floor: 254})
	if terms[0].Name == terms[1].Name {
		t.Errorf("two ranges share the term name %q", terms[0].Name)
	}
}

// TestFilterTablesWithdrawsWithLastPeer is AC-6: removing a peer's ttl block
// removes its listen-port term with its ICMP terms, and removing the last
// peer and range publishes no table at all.
func TestFilterTablesWithdrawsWithLastPeer(t *testing.T) {
	c := captureSeams(t)
	kept := gtsmPeer()
	gone := Peer{Addr: netip.MustParseAddr("2001:db8::9"), Port: 179, HopLimit: 255, Floor: 255}
	group := []Range{{Prefix: netip.MustParsePrefix("10.1.0.0/16"), Port: 179, Floor: 255}}

	if err := SetPeers([]Peer{kept, gone}, group); err != nil {
		t.Fatalf("SetPeers: %v", err)
	}
	if err := SetPeers([]Peer{kept}, nil); err != nil {
		t.Fatalf("SetPeers: %v", err)
	}
	if err := SetPeers(nil, nil); err != nil {
		t.Fatalf("SetPeers: %v", err)
	}
	if len(c.tables) != 3 {
		t.Fatalf("published %d times, want 3", len(c.tables))
	}
	names := map[string]bool{}
	for _, term := range c.tables[1][0].Chains[0].Terms {
		names[term.Name] = true
	}
	for _, absent := range []string{listenTermName(netip.PrefixFrom(gone.Addr, 128)), listenTermName(group[0].Prefix)} {
		if names[absent] {
			t.Errorf("term %q survived the removal of its source", absent)
		}
	}
	if !names[listenTermName(netip.PrefixFrom(kept.Addr, 32))] {
		t.Error("the kept peer lost its listen-port term")
	}
	if c.tables[2] != nil {
		t.Errorf("the last removal published %+v, want no table", c.tables[2])
	}
}

// TestGTSMHandsTheRouteHalfEveryPeer is the wiring proof for the transmit
// half, which is the one cell of RFC5082-3-2 that both families share.
func TestGTSMHandsTheRouteHalfEveryPeer(t *testing.T) {
	c := captureSeams(t)

	v4 := gtsmPeer()
	v6 := Peer{Addr: netip.MustParseAddr("2001:db8::1"), Port: 179, HopLimit: 255, Floor: 255}
	if err := SetPeers([]Peer{v6, v4}, nil); err != nil {
		t.Fatalf("SetPeers: %v", err)
	}

	if len(c.routesWanted) != 1 {
		t.Fatalf("applied routes %d times, want 1", len(c.routesWanted))
	}
	if len(c.routesWanted[0]) != 2 {
		t.Fatalf("applied %d routes, want one for each peer", len(c.routesWanted[0]))
	}
	// Sorted by address, so the kernel rule and route order does not move
	// between two applies that named the same peers.
	if c.routesWanted[0][0].Addr != v4.Addr || c.routesWanted[0][1].Addr != v6.Addr {
		t.Errorf("route order = %v, want it sorted by address", c.routesWanted[0])
	}
	for _, p := range c.routesWanted[0] {
		if p.HopLimit != 255 {
			t.Errorf("peer %s carries hop limit %d, want the 255 RFC 5082 Section 3 mandates", p.Addr, p.HopLimit)
		}
	}
}
