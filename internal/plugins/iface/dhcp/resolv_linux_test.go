//go:build linux

package ifacedhcp

import (
	"net"
	"os"
	"path/filepath"
	"testing"

	"github.com/insomniacslk/dhcp/dhcpv6"

	"github.com/ze-software/ze/internal/component/config/system"
)

const (
	resolvV4Server = "192.0.2.53"
	resolvV6Server = "2001:db8::53"
)

// resolvRig is a v6 rig whose leases go to a resolv.conf in a temp dir, and
// whose client already holds a DHCPv4 lease's server on the same interface.
func resolvRig(t *testing.T) (*v6Rig, string) {
	t.Helper()
	path := filepath.Join(t.TempDir(), "resolv.conf")
	resolvers := &system.Resolvers{}
	if err := resolvers.Configure(path, nil); err != nil {
		t.Fatalf("configure: %v", err)
	}
	r := newV6Rig(t, dHCPConfig{Resolvers: resolvers})
	r.client.setV4Resolvers([]string{resolvV4Server})
	return r, path
}

func resolvFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path) //nolint:gosec // test temp path
	if err != nil {
		t.Fatalf("read resolv.conf: %v", err)
	}
	return string(data)
}

// leaseWithDNSOnce is the 10/16/30 lease; the first Reply carries the DNS
// Recursive Name Server option and every later one omits it.
func leaseWithDNSOnce() func() []dhcpv6.Option {
	sent := false
	return func() []dhcpv6.Option {
		opts := lease10x16x30()
		if !sent {
			sent = true
			opts = append(opts, dhcpv6.OptDNS(net.ParseIP(resolvV6Server)))
		}
		return opts
	}
}

// TestRFC9915Section182105RenewWithoutDNSStopsUsingIt: a Renew Reply that
// omits the DNS option removes the DHCPv6 lease's server from resolv.conf and
// keeps the DHCPv4 lease's server.
//
// VALIDATES: RFC 9915 Section 18.2.10.5 "the client SHOULD stop using the
// previously received configuration information", per source (owner
// decision 2026-10-18, A-7): a v4 and a v6 source coexist, one is withdrawn.
// PREVENTS: the v6 server kept after the server stopped sending it, and the
// v6 withdrawal erasing the v4 lease's server.
func TestRFC9915Section182105RenewWithoutDNSStopsUsingIt(t *testing.T) {
	r, path := resolvRig(t)
	r.srv.serve = leaseServer(leaseWithDNSOnce(), true, false)
	r.startWorker()
	r.runUntil(seconds(5))
	want := "# Generated by ze\nnameserver " + resolvV4Server + "\nnameserver " + resolvV6Server + "\n"
	if got := resolvFile(t, path); got != want {
		t.Fatalf("after the lease, resolv.conf:\n%s\nwant:\n%s", got, want)
	}

	r.runUntil(seconds(11))
	if got := len(r.sentOf(dhcpv6.MessageTypeRenew)); got != 1 {
		t.Fatalf("%d RENEW sent by 11s, want 1", got)
	}
	want = "# Generated by ze\nnameserver " + resolvV4Server + "\n"
	if got := resolvFile(t, path); got != want {
		t.Errorf("after a Renew Reply without DNS, resolv.conf:\n%s\nwant:\n%s", got, want)
	}
}

// TestDHCPv6LeaseEndWithdrawsItsDNS: stopping the client ends the DHCPv6
// lease, and its server leaves resolv.conf while the DHCPv4 one stays.
//
// VALIDATES: a lease end removes its own servers only (A-7).
// PREVENTS: the old "stale DNS is better than no DNS" behavior, which kept a
// released lease's server.
func TestDHCPv6LeaseEndWithdrawsItsDNS(t *testing.T) {
	r, path := resolvRig(t)
	r.srv.serve = leaseServer(func() []dhcpv6.Option {
		return append(lease10x16x30(), dhcpv6.OptDNS(net.ParseIP(resolvV6Server)))
	}, true, false)
	r.startWorker()
	r.runUntil(seconds(5))
	if !r.stop() {
		t.Fatal("Stop did not return")
	}
	want := "# Generated by ze\nnameserver " + resolvV4Server + "\n"
	if got := resolvFile(t, path); got != want {
		t.Errorf("after Stop, resolv.conf:\n%s\nwant:\n%s", got, want)
	}
}

// TestDHCPv4TeardownWithdrawsItsDNS: tearing the DHCPv4 lease down removes
// its server and keeps another interface's.
//
// VALIDATES: teardownV4 withdraws the v4 source (A-7).
// PREVENTS: a released DHCPv4 lease's server left in resolv.conf.
func TestDHCPv4TeardownWithdrawsItsDNS(t *testing.T) {
	path := filepath.Join(t.TempDir(), "resolv.conf")
	resolvers := &system.Resolvers{}
	if err := resolvers.Configure(path, nil); err != nil {
		t.Fatalf("configure: %v", err)
	}
	if err := resolvers.SetLease(system.DHCPv6ResolverSource("eth1", "0"), []string{resolvV6Server}); err != nil {
		t.Fatalf("set lease: %v", err)
	}
	c := &DHCPClient{ifaceName: "eth0", unit: "0", config: dHCPConfig{Resolvers: resolvers}}
	c.setV4Resolvers([]string{resolvV4Server})
	c.teardownV4(&v4State{})
	want := "# Generated by ze\nnameserver " + resolvV6Server + "\n"
	if got := resolvFile(t, path); got != want {
		t.Errorf("after teardown, resolv.conf:\n%s\nwant:\n%s", got, want)
	}
}
