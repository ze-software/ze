// Design: docs/contributing/running-commands.md -- installing le's completion
// Related: ../words.go -- ze's callback, which writes the same record
//
// Package script holds what every Ze program's shell completion shares: the
// record a completion callback prints, and the script of a program whose whole
// grammar is answered by that callback. It imports nothing but textbuf, so the
// le binary uses it without linking ze's command client.
package script

import (
	"errors"
	"io"
	"strings"

	"github.com/ze-software/ze/internal/core/textbuf"
)

// The shells a callback-driven script is generated for.
const (
	ShellBash = "bash"
	ShellZsh  = "zsh"
	ShellFish = "fish"
)

// Shells answers the shells Generate accepts, in the order help lists them.
func Shells() []string { return []string{ShellBash, ShellZsh, ShellFish} }

// ErrShell is the refusal of a shell Generate does not write a script for.
var ErrShell = errors.New("no completion script for this shell")

// Program describes a program whose every completion comes from its own
// callback, `<program> completion words <word>...`.
type Program struct {
	// Name is the command word the reader types, and the stem of every shell
	// function the script defines: "le".
	Name string
	// Spellings are the command words the script registers, "le" and "./le".
	Spellings []string
	// Binary is the callback program, relative to the directory of the typed
	// command word: "bin/le". The script calls it directly, so the launcher
	// beside it never runs on a keystroke and never builds. When it is absent,
	// the typed word is called only if it is not a script (a launcher), so a
	// missing binary completes nothing and builds nothing.
	Binary string
}

// WriteRecord writes one shell-completion record: the candidate, a tab, its
// summary, a newline. Every Ze completion script reads that shape. A tab or a
// newline inside the summary makes the shell read one candidate as two, or
// read half the summary as a third field, so a summary carrying either one is
// FOLDED to single spaces, never cut: folding loses no word and decides
// nothing.
func WriteRecord(w io.Writer, candidate, summary string) error {
	if strings.ContainsAny(summary, "\n\r\t") {
		summary = textbuf.Join(strings.Fields(summary), " ")
	}
	var record textbuf.Buffer
	record.Str(candidate).Byte('\t').Str(summary).Byte('\n')
	_, err := io.WriteString(w, record.String())
	return err
}

// Generate answers the completion script of program for shell, or ErrShell
// for a shell it does not write.
func Generate(shell string, program Program) (string, error) {
	switch shell {
	case ShellBash:
		return bash(program), nil
	case ShellZsh:
		return zsh(program), nil
	case ShellFish:
		return fish(program), nil
	}
	return "", ErrShell
}

// bash registers every spelling by command word. Bash looks a completion up
// by the word as typed, so `./le` and `le` are two registrations of one
// function.
func bash(p Program) string {
	var tb textbuf.Buffer
	tb.Str("# ").Str(p.Name).Str(" bash completion -- generated by ").Str(p.Name).Str(" completion bash\n")
	tb.Str("# Install: eval \"$(./").Str(p.Name).Str(" completion bash)\"\n")
	tb.Str("# Or:      ./").Str(p.Name).Str(" completion bash > ~/.local/share/bash-completion/completions/").Str(p.Name).Str("\n\n")
	tb.Str("_").Str(p.Name).Str(`() {
    local word="${COMP_WORDS[0]}" target bin magic
    if [[ "${word}" == */* ]]; then
        target="${word}"
    else
        target=$(type -P -- "${word}" 2>/dev/null)
    fi
    [[ -n "${target}" ]] || return 0
    if [[ "${target}" == */* && -x "${target%/*}/`).Str(p.Binary).Str(`" ]]; then
        bin="${target%/*}/`).Str(p.Binary).Str(`"
    else
        # No binary beside the word: call the word only when it is not a
        # launcher script, so a keystroke never starts a build.
        IFS= read -r -n 2 magic < "${target}" 2>/dev/null
        [[ "${magic}" == '#!' ]] && return 0
        bin="${target}"
    fi
    local IFS=$'\n'
    COMPREPLY=($(compgen -W "$("${bin}" completion words "${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null | cut -f1)" -- "${COMP_WORDS[COMP_CWORD]}"))
}

complete -F _`).Str(p.Name)
	for _, spelling := range p.Spellings {
		tb.Byte(' ').Str(spelling)
	}
	return tb.Byte('\n').String()
}

// zsh registers every spelling with compdef and describes each candidate
// with its summary.
func zsh(p Program) string {
	var tb textbuf.Buffer
	tb.Str("#compdef ").Str(p.Name).Str("\n")
	tb.Str("# ").Str(p.Name).Str(" zsh completion -- generated by ").Str(p.Name).Str(" completion zsh\n")
	tb.Str("# Install: source <(./").Str(p.Name).Str(" completion zsh)\n")
	tb.Str("# Or:      ./").Str(p.Name).Str(" completion zsh > \"${fpath[1]}/_").Str(p.Name).Str("\"\n\n")
	tb.Str("_").Str(p.Name).Str(`() {
    local word=${words[1]} target bin magic line
    if [[ $word == */* ]]; then
        target=$word
    else
        target=${commands[$word]}
    fi
    [[ -n $target ]] || return 1
    if [[ $target == */* && -x ${target:h}/`).Str(p.Binary).Str(` ]]; then
        bin=${target:h}/`).Str(p.Binary).Str(`
    else
        # No binary beside the word: call the word only when it is not a
        # launcher script, so a keystroke never starts a build.
        read -r -k 2 magic < $target 2>/dev/null
        [[ $magic == '#!' ]] && return 1
        bin=$target
    fi
    local -a candidates
    for line in "${(@f)$($bin completion words "${(@)words[2,CURRENT]}" 2>/dev/null)}"; do
        [[ -n $line ]] || continue
        candidates+=("${${line%%$'\t'*}//:/\\:}:${line#*$'\t'}")
    done
    _describe -t commands '`).Str(p.Name).Str(` command' candidates
}

compdef _`).Str(p.Name)
	for _, spelling := range p.Spellings {
		tb.Byte(' ').Str(spelling)
	}
	return tb.Byte('\n').String()
}

// fish registers every spelling by command name. fish reads the callback's
// tab-separated records as candidate and description natively.
func fish(p Program) string {
	var tb textbuf.Buffer
	tb.Str("# ").Str(p.Name).Str(" fish completion -- generated by ").Str(p.Name).Str(" completion fish\n")
	tb.Str("# Install: ./").Str(p.Name).Str(" completion fish > ~/.config/fish/completions/").Str(p.Name).Str(".fish\n")
	tb.Str("# Or:      ./").Str(p.Name).Str(" completion fish | source\n\n")
	tb.Str("function __").Str(p.Name).Str(`_complete
    set -l tokens (commandline -opc) (commandline -ct)
    set -l word $tokens[1]
    set -l target $word
    if not string match -q -- '*/*' $word
        set target (command -s -- $word)
    end
    test -n "$target"; or return
    set -l dir (string replace -r -- '/[^/]*$' '' $target)
    set -l bin $dir/`).Str(p.Binary).Str(`
    if not string match -q -- '*/*' $target; or not test -x $bin
        # No binary beside the word: call the word only when it is not a
        # launcher script, so a keystroke never starts a build.
        read -l -n 2 magic < $target 2>/dev/null
        test "$magic" = '#!'; and return
        set bin $target
    end
    $bin completion words $tokens[2..-1] 2>/dev/null
end
`)
	for _, spelling := range p.Spellings {
		tb.Str("complete -c ").Str(spelling).Str(" -f -a '(__").Str(p.Name).Str("_complete)'\n")
	}
	return tb.String()
}
