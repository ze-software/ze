// delegation is one RIR's file, in the format the five publish: pipe-separated
// records, a header line, and rows for every resource type.
const delegation = "2|ripencc|20260826|1|0|20260826|+0000\n" +
	"ripencc|*|asn|*|3|summary\n" +
	"ripencc|EU|asn|1|1|19930901|allocated\n" +
	"ripencc|EU|asn|2|2|19930901|assigned\n" +
	"ripencc|EU|asn|100|1|19930901|reserved\n" +
	"ripencc|EU|ipv4|10.0.0.0|256|19930901|allocated\n" +
	"# a comment\n" +
	"\n"

// fetchFrom answers a fetch that serves one body per URL and records the order.
func fetchFrom(bodies map[string]string, asked *[]string) Fetch {
	return func(_ context.Context, url string) ([]byte, error) {
		*asked = append(*asked, url)
		body, held := bodies[url]
		if !held {
			return nil, errors.New("no such file")
		}
		return []byte(body), nil
	}
}

// everyRIR answers a body for each of the five delegation files, so a whole run
// reaches the write.
func everyRIR(body string) map[string]string {
	bodies := map[string]string{}
	for _, url := range delegationURLs {
		bodies[url] = body
	}
	return bodies
}

func tree(t *testing.T) string {
	t.Helper()

	root := t.TempDir()
	if err := os.MkdirAll(filepath.Join(root, filepath.Dir(outputFile)), 0o755); err != nil {
		t.Fatalf("create the irr package directory: %v", err)
	}
	return root
}

// VALIDATES: only allocated and assigned ASN records of a known registry are
// taken, and each becomes a half-open range the record's count describes.
// PREVENTS: a reserved or unallocated block being published as delegated, and
// an off-by-one at the end of every range.
func TestOnlyAllocatedAndAssignedASNRecordsAreTaken(t *testing.T) {
	got, err := parseDelegation(strings.NewReader(delegation))
	if err != nil {
		t.Fatalf("parseDelegation: %v", err)
	}

	if len(got) != 2 {
		t.Fatalf("the parse took %d records, want 2: %+v", len(got), got)
	}
	if got[0].Start != 1 || got[0].End != 1 || got[0].RIR != "RIPE" || got[0].Whois != "whois.ripe.net" {
		t.Errorf("the first record is %+v, want AS1 alone at RIPE", got[0])
	}
	if got[1].Start != 2 || got[1].End != 3 {
		t.Errorf("the second record is %+v, want AS2 to AS3", got[1])
	}
}

// VALIDATES: adjacent and overlapping ranges of one registry collapse, and two
// registries never do.
// PREVENTS: a table that claims one RIR owns a block another one delegates.
func TestCollapseJoinsOneRegistryAndNeverTwo(t *testing.T) {
	got := collapse([]Entry{
		{Start: 1, End: 2, RIR: "RIPE"},
		{Start: 3, End: 4, RIR: "RIPE"},
		{Start: 4, End: 9, RIR: "RIPE"},
		{Start: 10, End: 11, RIR: "ARIN"},
		{Start: 12, End: 13, RIR: "RIPE"},
	})

	if len(got) != 3 {
		t.Fatalf("collapse answered %d ranges, want 3: %+v", len(got), got)
	}
	if got[0].Start != 1 || got[0].End != 9 {
		t.Errorf("the first range is %+v, want AS1 to AS9", got[0])
	}
	if got[1].RIR != "ARIN" || got[2].RIR != "RIPE" {
		t.Errorf("the registries are %s and %s, want ARIN then RIPE", got[1].RIR, got[2].RIR)
	}
}

// VALIDATES: the generated table carries the interned constant names, the
// generation date and the seed variable the irr package reads.
// PREVENTS: a table that does not compile as the package it declares, and
// per-entry string allocation where rir.go already holds the constants.
func TestGeneratedTableIsByteExact(t *testing.T) {
	got := string(tableSource([]Entry{
		{Start: 1, End: 9, RIR: "RIPE", Whois: "whois.ripe.net"},
		{Start: 10, End: 11, RIR: "ARIN", Whois: "whois.arin.net"},
	}, "2026-08-26"))

	want := "// Design: docs/architecture/resolve.md -- compiled RIR delegation seed\n//\n" +
		"// Code generated by scripts/codegen/iana_asn.go; DO NOT EDIT.\n" +
		"// Source: RIR delegation files (RIPE, ARIN, APNIC, AFRINIC, LACNIC)\n" +
		"// Generated: 2026-08-26\n" +
		"// This is seed data for zefs prepopulation. Runtime updates via `ze update bgp irr all`.\n\n" +
		"package irr\n\n" +
		"// seedRIRTable is the compiled-in RIR delegation data.\n" +
		"// Used as fallback when zefs has no data or as initial seed.\n" +
		"var seedRIRTable = []RIREntry{\n" +
		"\t{1, 9, RIRRIPE, WhoisRIPE},\n" +
		"\t{10, 11, RIRARIN, WhoisARIN},\n" +
		"}\n"

	if got != want {
		t.Errorf("the table is\n%q\nwant\n%q", got, want)
	}
}

// VALIDATES: a whole run fetches all five delegation files and writes the table.
// PREVENTS: a seed built from a subset, which hands one RIR's blocks to whichever
// registry did answer.
func TestWriteFetchesEveryRegistryAndWritesTheTable(t *testing.T) {
	root := tree(t)
	var asked []string

	report, err := Write(context.Background(), root, fetchFrom(everyRIR(delegation), &asked))
	if err != nil {
		t.Fatalf("Write: %v", err)
	}

	if len(asked) != len(delegationURLs) {
		t.Errorf("the run fetched %d files, want %d", len(asked), len(delegationURLs))
	}
	if report.Records != 2*len(delegationURLs) {
		t.Errorf("the run took %d records, want two per registry", report.Records)
	}
	if report.Ranges != 1 {
		t.Errorf("the run wrote %d ranges, want one collapsed range", report.Ranges)
	}

	body, err := os.ReadFile(filepath.Join(root, outputFile))
	if err != nil {
		t.Fatalf("read the generated table: %v", err)
	}
	if !strings.Contains(string(body), "{1, 3, RIRRIPE, WhoisRIPE},") {
		t.Errorf("the generated table does not carry the collapsed range:\n%s", body)
	}
}

// VALIDATES: a run that parsed no ASN record writes NOTHING and answers an
// error.
// PREVENTS: the fail-open this port fixes. scripts/codegen/iana_asn.go writes
// whatever it parsed, so five HTTP 200 responses carrying no ASN record leave an
// EMPTY seedRIRTable committed and the run reporting success. Every IRR lookup
// then falls back to nothing, and no test of the irr package can see it, because
// the table it reads is the table that was emptied.
func TestARunThatParsedNothingWritesNothing(t *testing.T) {
	root := tree(t)
	var asked []string

	_, err := Write(context.Background(), root, fetchFrom(everyRIR("2|ripencc|20260826|0|0|20260826|+0000\n"), &asked))
	if err == nil {
		t.Fatal("Write accepted five answers holding no ASN record")
	}
	if _, statErr := os.Stat(filepath.Join(root, outputFile)); !os.IsNotExist(statErr) {
		t.Errorf("Write created the table from nothing: %v", statErr)
	}
}

// VALIDATES: a registry that does not answer stops the run before anything is
// written.
// PREVENTS: a table missing one RIR's whole delegation, which reads as "this ASN
// belongs to nobody" for every AS number that registry holds.
func TestOneRegistryFailingStopsTheRun(t *testing.T) {
	root := tree(t)
	bodies := everyRIR(delegation)
	delete(bodies, delegationURLs[2])
	var asked []string

	if _, err := Write(context.Background(), root, fetchFrom(bodies, &asked)); err == nil {
		t.Fatal("Write accepted a run where one registry did not answer")
	}
	if _, statErr := os.Stat(filepath.Join(root, outputFile)); !os.IsNotExist(statErr) {
		t.Errorf("Write left a partial table behind: %v", statErr)
	}
}

// VALIDATES: the table is built in memory and written once.
// PREVENTS: a truncated file. os.Create truncates before the first byte is
// written, so a generator that streams and fails midway leaves the irr package
// holding half a table that does not compile.
func TestTheTableIsWrittenInOneCall(t *testing.T) {
	root := tree(t)
	// A read-only directory: the write fails, and the point is that it fails
	// BEFORE the existing file is touched.
	write(t, root, outputFile, "package irr\n\nvar seedRIRTable = []RIREntry{}\n")
	before, err := os.ReadFile(filepath.Join(root, outputFile))
	if err != nil {
		t.Fatalf("read the existing table: %v", err)
	}

	var asked []string
	bodies := everyRIR(delegation)
	delete(bodies, delegationURLs[0])
	if _, writeErr := Write(context.Background(), root, fetchFrom(bodies, &asked)); writeErr == nil {
		t.Fatal("Write accepted a failed fetch")
	}

	after, err := os.ReadFile(filepath.Join(root, outputFile))
	if err != nil {
		t.Fatalf("read the table after the failed run: %v", err)
	}
	if !bytes.Equal(after, before) {
		t.Errorf("a failed run rewrote the table:\n%s", after)
	}
}

// VALIDATES: the report renders in the words the script printed.
// PREVENTS: a report a developer cannot read at a terminal.
func TestTheReportRendersTheScriptWording(t *testing.T) {
	report := WriteReport{File: outputFile, Ranges: 12, Records: 34}
	want := "wrote internal/component/resolve/irr/rir_table.go (12 collapsed ranges from 34 records)\n"
	if got := report.Text(); got != want {
		t.Errorf("the report renders\n%q\nwant\n%q", got, want)
	}
}

func write(t *testing.T, root, rel, content string) {
	t.Helper()

	path := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("create the fixture directory for %s: %v", rel, err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write the fixture %s: %v", rel, err)
	}
}
