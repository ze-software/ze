// Design: docs/architecture/command-ownership.md -- YANG as data, generated glue wires it in
//
// Package yangglue generates the embed.go and register.go beside every .yang
// file in the tree. The generated Go is what wires a YANG module into the
// config/yang registry: an //go:embed directive per module, and an init() that
// calls RegisterModule with the module's FILE NAME as its key.
//
// The pair is a generator and its read-only twin. `le yang-glue write` writes
// the glue; `le yang-glue check` regenerates it in memory and reports every
// file that disagrees, which is what makes a generated file gateable
// (ze-yang-glue-check).
//
// Two directories are excluded and both exclusions are load-bearing.
// internal/component/config/yang is the registry the glue registers INTO, so
// glue written there would register the registry with itself. internal/test
// holds fixture schemas the suites feed to a parser, never modules ze serves.
package yangglue

import (
	"bytes"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"unicode"

	"github.com/ze-software/ze/internal/core/textbuf"
	"github.com/ze-software/ze/letools/lepath"
)

// generatedHeader opens every file this tool writes. It names the SCRIPT
// because the committed glue names the script: changing the line would make
// every generated file in the tree stale at once, and the two halves of the
// port would stop agreeing about bytes. It moves when the script does.
const generatedHeader = "// Code generated by scripts/codegen/yang_glue.go; DO NOT EDIT.\n"

// registryPackage is the config/yang package, relative to internal/. It is the
// registry the generated init() calls, so it is never itself a schema package.
var registryPackage = filepath.Join("component", "config", "yang")

// discover answers every yang/ directory under root holding at least one .yang
// file, sorted.
//
// A directory the walk LISTS and cannot read stops the run. For a generator
// that is the only safe answer: a package passed over silently is a set of YANG
// modules that vanish from the composition root, and the write half would then
// commit the tree with them gone.
func discover(root string) ([]string, error) {
	internalDir := filepath.Join(root, "internal")

	var dirs []string

	err := filepath.WalkDir(internalDir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		if strings.Contains(filepath.ToSlash(path), "/internal/test/") {
			return filepath.SkipDir
		}
		if d.Name() != "yang" {
			return nil
		}
		if rel, relErr := filepath.Rel(internalDir, path); relErr == nil && rel == registryPackage {
			return filepath.SkipDir
		}

		entries, readErr := os.ReadDir(path)
		if readErr != nil {
			return readErr
		}
		for _, entry := range entries {
			if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".yang") {
				dirs = append(dirs, path)
				break
			}
		}
		// A yang/ directory holds modules, never another yang/ directory.
		return filepath.SkipDir
	})
	if err != nil {
		return nil, err
	}

	slices.Sort(dirs)

	return dirs, nil
}

// modulesIn answers the .yang file names of one directory, sorted.
func modulesIn(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	var modules []string
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".yang") {
			modules = append(modules, entry.Name())
		}
	}

	slices.Sort(modules)

	return modules, nil
}

// embedSource renders the embed.go of one schema package: one //go:embed
// directive and one string variable per module.
func embedSource(modules []string) []byte {
	var tb textbuf.Buffer

	tb.Str(generatedHeader)
	tb.Str("\npackage yang\n")
	tb.Str("\nimport _ \"embed\"\n")

	for _, module := range modules {
		tb.Str("\n//go:embed ").Str(module).Byte('\n')
		tb.Str("var ").Str(varName(module)).Str(" string\n")
	}

	return slices.Clone(tb.Bytes())
}

// registerSource renders the register.go of one schema package: an init() that
// registers each module under its FILE NAME, which is the key the loader reads.
func registerSource(modules []string, module string) []byte {
	var tb textbuf.Buffer

	tb.Str(generatedHeader)
	tb.Str("\npackage yang\n")
	tb.Str("\nimport (\n\tconfigyang \"").Str(module).Str("/internal/component/config/yang\"\n)\n")
	tb.Str("\nfunc init() {\n")

	for _, name := range modules {
		tb.Str("\tconfigyang.RegisterModule(\"").Str(name).Str("\", ").Str(varName(name)).Str(")\n")
	}

	tb.Str("}\n")

	return slices.Clone(tb.Bytes())
}

