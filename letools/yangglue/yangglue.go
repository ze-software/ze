// varName answers the Go variable name of one module file: ze-host-cmd.yang
// becomes ZeHostCmdYANG.
func varName(filename string) string {
	var tb textbuf.Buffer

	for part := range strings.SplitSeq(strings.TrimSuffix(filename, ".yang"), "-") {
		if upper, listed := acronyms[strings.ToLower(part)]; listed {
			tb.Str(upper)
			continue
		}
		tb.Str(titleCase(part))
	}
	tb.Str("YANG")

	return tb.String()
}

// titleCase upper-cases the first rune and leaves the rest, which is what a
// hyphen-separated name part owes.
func titleCase(s string) string {
	if s == "" {
		return s
	}
	runes := []rune(s)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}

// glue is one generated file: where it goes, and what it must hold.
type glue struct {
	path string
	want []byte
}

// derive answers every generated file the tree owes, and how many schema
// packages produced them.
func derive(root string) (files []glue, dirs int, err error) {
	found, err := discover(root)
	if err != nil {
		return nil, 0, err
	}
	if len(found) == 0 {
		return nil, 0, nil
	}

	module, err := lepath.Module(root)
	if err != nil {
		return nil, 0, err
	}

	for _, dir := range found {
		modules, listErr := modulesIn(dir)
		if listErr != nil {
			return nil, 0, listErr
		}
		if len(modules) == 0 {
			continue
		}
		files = append(files,
			glue{path: filepath.Join(dir, "embed.go"), want: embedSource(modules)},
			glue{path: filepath.Join(dir, "register.go"), want: registerSource(modules, module)},
		)
	}

	return files, len(found), nil
}

// Check reports every generated file that disagrees with the .yang files beside
// it. It writes nothing.
func Check(root string) (CheckReport, error) {
	files, dirs, err := derive(root)
	if err != nil {
		return CheckReport{}, err
	}

	report := CheckReport{Dirs: dirs}

	for _, file := range files {
		got, readErr := os.ReadFile(file.path) //nolint:gosec // a build tool reads the checkout it was pointed at
		if readErr != nil || !bytes.Equal(got, file.want) {
			report.Stale = append(report.Stale, relativeTo(root, file.path))
		}
	}

	return report, nil
}

// Write generates the glue, and answers the files whose bytes changed. A file
// that already agrees is left alone, so `make generate` moves no mtime it does
// not have to.
func Write(root string) (WriteReport, error) {
	files, dirs, err := derive(root)
	if err != nil {
		return WriteReport{}, err
	}

	report := WriteReport{Dirs: dirs}

	for _, file := range files {
		got, readErr := os.ReadFile(file.path) //nolint:gosec // a build tool reads the checkout it was pointed at
		if readErr == nil && bytes.Equal(got, file.want) {
			continue
		}
		if err := os.WriteFile(file.path, file.want, 0o644); err != nil { //nolint:gosec // generated source, read by everyone who reads the tree
			return WriteReport{}, err
		}
		report.Written = append(report.Written, relativeTo(root, file.path))
	}

	return report, nil
}

// relativeTo answers a path as the tree sees it. A generated file's identity is
// its place in the checkout, and an absolute path names this machine's tmp
// directory as much as it names the file.
func relativeTo(root, path string) string {
	rel, err := filepath.Rel(root, path)
	if err != nil {
		return filepath.ToSlash(path)
	}
	return filepath.ToSlash(rel)
}
