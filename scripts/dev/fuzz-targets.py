#!/usr/bin/env python3
"""Generate mk/test-fuzz-targets.mk: one fuzz invocation per `func Fuzz` target.

Replaces the hand-maintained enumeration that used to live in mk/test-fuzz.mk.
The source of truth is "a package under internal/ has a `func Fuzz`", not a name
list a human keeps in sync: this generator walks the tree, resolves each target
to its exact package directory, and emits one anchored invocation per target.
Registration over hardcoding -- a new fuzzer (ISIS/OSPF and every future one) is
included by existing, not by remembering to edit the makefile.

Two invariants Go fuzz imposes, both handled here:
  * Within one package a target name may be a prefix of another
    (FuzzParseVPN vs FuzzParseVPNAddPath), so the name is emitted as an anchored
    regexp `-fuzz=^<Name>$` or the run errors "matches more than one fuzz target".
  * A tree may hold sibling packages (internal/plugins/isis/{packet,yang}), so
    the exact single-package path is emitted, never `./.../...`, or the run
    errors "matches more than one package".

The emitted fragment is committed and gated: `make generate` writes it (from
generate: in the Makefile) and `--check` regenerates in memory and diffs the
committed copy, exiting non-zero with "<path> is stale; run make generate" on
drift. This mirrors scripts/codegen/plugin_imports.go --check for the plugin
composition root exactly, so a forgotten regen is a hard verify-gate red rather
than a silently-skipped fuzzer.

Usage:
    python3 scripts/dev/fuzz-targets.py            # regenerate mk/test-fuzz-targets.mk
    python3 scripts/dev/fuzz-targets.py --check    # exit 1 if the fragment is stale
    python3 scripts/dev/fuzz-targets.py --root DIR  # operate on another tree (tests)
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# Keep in lockstep with the historic hand-list budget (mk/test-fuzz.mk): a short
# 10s-per-target stage suitable for scheduled CI, 60s hard timeout per target.
FUZZTIME = "10s"
TIMEOUT = "60s"

OUTPUT_REL = Path("mk") / "test-fuzz-targets.mk"

# Directories that never hold fuzz targets and must not be walked.
SKIP_DIRS = {"vendor", "tmp", "testdata", "node_modules", ".git"}

FUNC_FUZZ_RE = re.compile(r"^func (Fuzz[A-Za-z0-9_]+)\s*\(", re.MULTILINE)


def discover(root: Path) -> list[tuple[str, str]]:
    """Return sorted (fuzz_name, package_path) for every `func Fuzz` in internal/.

    package_path is the exact single-package directory (e.g.
    "./internal/plugins/isis/packet"), never a `/...` wildcard, so Go fuzz never
    reports "matches more than one package".
    """
    base = root / "internal"
    targets: set[tuple[str, str]] = set()
    if not base.is_dir():
        return []
    for path in base.rglob("*_test.go"):
        if any(part in SKIP_DIRS for part in path.relative_to(root).parts):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        names = FUNC_FUZZ_RE.findall(text)
        if not names:
            continue
        pkg = "./" + path.parent.relative_to(root).as_posix()
        for name in names:
            targets.add((name, pkg))
    # Sort by package then name: stable, reviewable, and groups a package's
    # targets together in the emitted recipe.
    return sorted(targets, key=lambda t: (t[1], t[0]))


def render(targets: list[tuple[str, str]]) -> str:
    """Render the committed mk/test-fuzz-targets.mk fragment.

    Emits the whole `ze-fuzz-test` rule so mk/test-fuzz.mk can `include` this
    file in place of its former hand-list. `$$` is a make-escaped `$`: after make
    expands the recipe, `go test` sees `-fuzz=^<Name>$`.

    The rule is emitted as the ADMISSION PAIR every heavy target in this
    repository uses: the public name calls scripts/dev/ze-run.sh, and
    `_ze-fuzz-test-impl` carries the body. Several sessions share one checkout
    and one machine, and this target starts one Go test binary per fuzz target,
    so running it unadmitted is what the wrapper exists to prevent
    (plan/spec-shared-machine-job-admission.md). A generated file cannot be
    hand-wrapped, so the shape has to come from here.
    """
    lines = [
        "# Code generated by scripts/dev/fuzz-targets.py; DO NOT EDIT.",
        "#",
        "# One anchored `-fuzz=^<Name>$` invocation per discovered `func Fuzz`",
        "# target under internal/. Source of truth: a package has a `func Fuzz`.",
        "# Add a fuzzer and run `make generate`; never hand-edit this file.",
        "",
        "ze-fuzz-test:",
        "\t@scripts/dev/ze-run.sh ze-fuzz-test $(MAKE) --no-print-directory _ze-fuzz-test-impl",
        "",
        "_ze-fuzz-test-impl:",
        '\t@echo "Running ze fuzz tests..."',
    ]
    for name, pkg in targets:
        lines.append(
            f"\t$(GO_TEST) -fuzz=^{name}$$ -fuzztime={FUZZTIME} -timeout={TIMEOUT} {pkg}"
        )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed fragment is stale instead of rewriting it",
    )
    parser.add_argument(
        "--root",
        default=None,
        help="repository root (defaults to the repo this script lives in)",
    )
    args = parser.parse_args(argv)

    root = (
        Path(args.root).resolve() if args.root else Path(__file__).resolve().parents[2]
    )
    output = root / OUTPUT_REL
    content = render(discover(root))

    if args.check:
        current = output.read_text(encoding="utf-8") if output.exists() else ""
        if current != content:
            # Same phrasing as scripts/codegen/plugin_imports.go so the fix is
            # identical across generated-and-verified artifacts.
            print(f"{OUTPUT_REL.as_posix()} is stale; run make generate")
            return 1
        n = content.count("$(GO_TEST)")
        print(f"checked {n} fuzz targets, {OUTPUT_REL.as_posix()} up to date")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    n = content.count("$(GO_TEST)")
    print(f"wrote {output} ({n} fuzz targets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
