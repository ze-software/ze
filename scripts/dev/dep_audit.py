def repo_root() -> str:
    return subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()


def module_path(root: str) -> str:
    with open(os.path.join(root, "go.mod"), encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("module "):
                return line.split(None, 1)[1].strip()
    raise SystemExit("go.mod: no module line found")


def is_registration_importer(rel: str) -> bool:
    """True for files that only blank-import for side-effect registration."""
    if rel.endswith("/all/all.go"):
        return True
    # Per-feature compile-out files generated next to all.go (all_<tag>.go,
    # //go:build <tag>) are the same registration composition root, just gated
    # behind a build tag. They MUST count as registration importers, or a gated
    # ENGINE's blank import moving from all.go into all_<tag>.go reads as a
    # feature dependency (spec-feature-gate-8: the routing protocols are the
    # first gated packages that are also sdk.NewWithConn engines).
    parent, _, base = rel.rpartition("/")
    if (
        parent.endswith("/plugin/all")
        and base.startswith("all_")
        and base.endswith(".go")
    ):
        return True
    if rel.startswith("cmd/ze/") and (
        "dispatch" in rel
        or rel.endswith("_imports.go")
        or re.search(r"/setup_features_[^/]+\.go$", rel)
    ):
        return True
    return False


def collect_edges(root: str, module: str) -> dict:
    """imported package import-path -> set of importer file paths (repo-relative)."""
    edges = defaultdict(set)
    imp_re = re.compile(r'"(' + re.escape(module) + r'/[^"]+)"')
    modcache_rel = os.path.join("gokrazy", "modcache")
    for dirpath, dirs, files in os.walk(root):
        dirs[:] = [
            d
            for d in dirs
            if d not in (".git", ".claude", "vendor", "tmp", "node_modules")
            # Skip the gokrazy module cache: it holds extracted copies of external
            # modules AND a self-copy of ze (github.com/ze-software/ze@vX/...),
            # regenerated by appliance builds. Auditing those duplicates the
            # working tree's already-baselined edges and is not first-party source.
            and os.path.relpath(os.path.join(dirpath, d), root) != modcache_rel
        ]
        for f in files:
            if not f.endswith(".go"):
                continue
            full = os.path.join(dirpath, f)
            rel = os.path.relpath(full, root)
            try:
                txt = open(full, encoding="utf-8", errors="ignore").read()
            except OSError:
                continue
            for m in imp_re.finditer(txt):
                edges[m.group(1)].add(rel)
    return edges


def classify(area: str, root: str, module: str, edges: dict, engines: set) -> list:
    base = module + "/" + area
    area_dir = os.path.join(root, area)
    out = []
    for top in sorted(os.listdir(area_dir)):
        if not os.path.isdir(os.path.join(area_dir, top)):
            continue
        subsystem = area + "/" + top
        pkg_prefix = base + "/" + top
        own_rel_prefix = os.path.join(area, top) + os.sep
        external, registration, tests = set(), set(), set()
        for imported, importers in edges.items():
            if imported != pkg_prefix and not imported.startswith(pkg_prefix + "/"):
                continue
            for imp in importers:
                if imp.startswith(own_rel_prefix):
                    continue  # inside its own subtree
                if imp.endswith("_test.go"):
                    tests.add(imp)
                elif is_registration_importer(imp):
                    registration.add(imp)
                else:
                    external.add(imp)
        # "wired" = blank-imported by a composition root (the generated all.go OR
        # cmd/ze dispatch), per is_registration_importer. This is the authoritative
        # "the build treats this subsystem as a plugin/command" signal -- it reuses
        # the generator's output (all.go) plus the dispatch root, instead of a
        # per-mechanism registration grep that mis-sends *-cmd dirs to core
        # (umbrella blocker B-1). It catches every shape: registry.Register,
        # RegisterRPCs, RegisterBackend, doctor checks, and *-cmd verb providers.
        is_registered = len(registration) > 0
        is_engine = subsystem in engines
        out.append(
            {
                "name": top,
                "external": sorted(external),
                "registration": sorted(registration),
                "tests": sorted(tests),
                "is_candidate": len(external) == 0,
                "is_registered": is_registered,
                "is_engine": is_engine,
                # a genuine internal/core candidate: a leaf nothing depends on that
                # no composition root wires and that is not a config-driven engine.
                "core_candidate": len(external) == 0
                and not is_registered
                and not is_engine,
            }
        )
    return out


# ---------------------------------------------------------------------------
# Disableable-feature direct-import audit (feature-gate compile-out)
# ---------------------------------------------------------------------------
#
# A compile-out-able feature (guarded by //go:build ze_<feature>) must be reached
# ONLY through build-tag-gated registration. A direct functional import from
# always-on (untagged) code pins the package into every binary, defeating the
# compile-out. This audit flags any non-test, out-of-tree file that imports a
# disableable package without the gating build tag.
#
# The disableable set is NOT hand-maintained here: it is loaded from the
# feature-gate manifest (feature-gates.txt), the single source of truth shared
# with the generator, the Makefile, and the test runner. Add a gate by adding
# one line to that file. See plan/spec-feature-gate-0-umbrella.md,
# ai/rules/plugins.md, and ai/rules/architecture.md.
FEATURE_GATES_MANIFEST = "feature-gates.txt"
GOLANGCI = ".golangci.yml"
# Non-feature build tags that legitimately appear in .golangci.yml build-tags
# alongside the per-feature gate tags (the lint build is ze_core + every gate).
GOLANGCI_BASE_TAGS = {"ze_core"}

# Trees that are NOT part of the production `ze` daemon and therefore cannot pin
# a disableable feature into it. The chaos orchestrator (internal/chaos/*) is the
# ze-chaos binary's code, reached from cmd/ze only under //go:build ze_chaos
# (cmd/ze/ze_chaos_run.go); ze-chaos is built `-tags ze_chaos` and always wants
# the feature it imports. Test-support packages (internal/test/*) are likewise
# not in the daemon. A direct, untagged import of a disableable feature from
# these trees is NOT a compile-out violation. cmd/ze is deliberately NOT listed:
# the gated service/seam files live there and MUST carry the build tag, so they
# stay in scope. Mirrors the engine gate's NON_FEATURE_PREFIXES rationale.
DISABLEABLE_NONPROD_PREFIXES = (
    "internal/chaos/",
    "internal/test/",
    # internal/perf is the ze-perf binary's benchmark harness, reached from
    # cmd/ze only under //go:build ze_perf; ze-perf is built with the feature it
    # measures forced on. scripts/ holds build-time tooling (codegen, doc and
    # grammar checkers) run with `go run`, never linked into ze -- several are
    # //go:build ignore. Neither tree can pin a disableable feature into the
    # daemon, so an untagged import from them is not a compile-out violation.
    "internal/perf/",
    "scripts/",
)


def load_feature_gates(root: str) -> dict:
    """Parse feature-gates.txt -> {gated-package: build-tag}.

    Lines are "<tag> <pkg>"; '#' comments and blanks are ignored. This is the
    DISABLEABLE map: the package each //go:build ze_<tag> guards.
    """
    path = os.path.join(root, FEATURE_GATES_MANIFEST)
    gates = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 2:
                raise SystemExit(
                    f"{FEATURE_GATES_MANIFEST}: malformed line {line!r} "
                    "(want '<tag> <pkg>')"
                )
            tag, pkg = parts[0], parts[1]
            gates[pkg] = tag
    return gates


def _tag_required(constraint: str, tag: str) -> bool:
    """True if a //go:build constraint string positively requires tag."""
    if re.search(r"!\s*" + re.escape(tag) + r"\b", constraint):
        return False
    return re.search(r"\b" + re.escape(tag) + r"\b", constraint) is not None


def file_requires_tag(root: str, rel: str, tag: str) -> bool:
    """True if file rel carries a //go:build constraint requiring tag."""
    try:
        txt = open(os.path.join(root, rel), encoding="utf-8", errors="ignore").read()
    except OSError:
        return False
    for line in txt.splitlines():
        s = line.strip()
        if s.startswith("//go:build"):
            return _tag_required(s[len("//go:build") :], tag)
        if s and not s.startswith("//"):
            return False  # reached code before any build constraint
    return False


def _same_feature_importer(imp: str, tag: str, disableable: dict) -> bool:
    """True if file imp lives inside ANY package gated by the same tag.

    Such an importer belongs to the same feature: it is dropped together with the
    imported package when the tag is off, so it cannot pin that package into a
    no-tag build (it is not an always-on pin). This generalises the old
    own-subtree skip to multi-package features -- a routing protocol's engine,
    transport, and cli sub-packages all share one tag and freely import each
    other (spec-feature-gate-8). The gate still independently verifies each gated
    package has no truly always-on (untagged, cross-feature) importer.
    """
    for other_pkg, other_tag in disableable.items():
        if other_tag == tag and (imp == other_pkg or imp.startswith(other_pkg + "/")):
            return True
    return False


def disableable_violations(
    root: str, module: str, edges: dict, disableable=None
) -> list:
    """Always-on files that directly import a disableable feature package."""
    if disableable is None:
        disableable = load_feature_gates(root)
    out = []
    for pkg, tag in sorted(disableable.items()):
        import_path = module + "/" + pkg
        for imp in sorted(edges.get(import_path, ())):
            if _same_feature_importer(imp, tag, disableable):
                continue  # same feature (same tag) -- dropped together, not a pin
            if imp.endswith("_test.go"):
                continue  # tests may import the package directly
            if any(imp.startswith(p) for p in DISABLEABLE_NONPROD_PREFIXES):
                continue  # not in the production ze daemon (ze-chaos / test support)
            if not file_requires_tag(root, imp, tag):
                out.append((imp, pkg, tag))
    return out


def disableable_gate(root: str, module: str, edges: dict) -> int:
    viol = disableable_violations(root, module, edges)
    if not viol:
        return 0
    print(
        "FAIL: disableable feature(s) imported by always-on code -- breaks compile-out:",
        file=sys.stderr,
    )
    for imp, pkg, tag in viol:
        print(f"  {imp} imports {pkg} without //go:build {tag}", file=sys.stderr)
    print(
        "  Rule: a compile-out-able feature is reached ONLY via build-tag-gated "
        "registration (ai/rules/architecture.md). Gate the importer with "
        "//go:build <tag> or route it through the service construction registry.",
        file=sys.stderr,
    )
    return 2


def parse_golangci_build_tags(root: str) -> set:
    """Read the `build-tags:` list from .golangci.yml (no YAML dependency).

    Captures the `- <tag>` items under the `build-tags:` key and stops at the
    next non-list line, mirroring the file's simple two-space-indented layout.
    """
    path = os.path.join(root, GOLANGCI)
    tags = set()
    capturing = False
    item_re = re.compile(r"^\s*-\s*(\S+)\s*$")
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            # Strip any inline "# ..." comment (YAML allows them); build tags are
            # Go identifiers and never contain '#', so this is lossless.
            line = raw.split("#", 1)[0]
            if re.match(r"^\s*build-tags:\s*$", line):
                capturing = True
                continue
            if not capturing:
                continue
            m = item_re.match(line)
            if m:
                tags.add(m.group(1))
                continue
            if line.strip() == "":
                continue  # blank or comment-only line inside the list
            break  # reached the next key; the build-tags list is done
    return tags


def golangci_drift_gate(root: str) -> int:
    """.golangci.yml build-tags is static YAML (it cannot read the manifest), so
    this catches drift: its feature tags MUST equal the manifest's gate tags.

    This is the one consumer that does not derive automatically; every other
    consumer reads feature-gates.txt directly. Keeping the lint build's tag set
    in lock-step ensures the //go:build ze_<feature> files get lint coverage.
    """
    manifest_tags = set(load_feature_gates(root).values())
    golangci_tags = parse_golangci_build_tags(root)
    golangci_features = golangci_tags - GOLANGCI_BASE_TAGS
    if golangci_features == manifest_tags:
        return 0
    missing = manifest_tags - golangci_features
    extra = golangci_features - manifest_tags
    print(
        f"FAIL: {GOLANGCI} build-tags drifted from {FEATURE_GATES_MANIFEST}:",
        file=sys.stderr,
    )
    if missing:
        print(f"  add to {GOLANGCI} build-tags: {sorted(missing)}", file=sys.stderr)
    if extra:
        print(
            f"  remove from {GOLANGCI} build-tags (no such gate): {sorted(extra)}",
            file=sys.stderr,
        )
    print(
        f"  build-tags must be {sorted(GOLANGCI_BASE_TAGS)} + every gate tag in "
        f"{FEATURE_GATES_MANIFEST}.",
        file=sys.stderr,
    )
    return 2


