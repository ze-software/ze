def _parse_string_list(root: str, name: str) -> list:
    path = os.path.join(root, GENERATOR)
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    m = re.search(rf"var {name} = \[\]string\{{(.*?)\}}", text, re.DOTALL)
    if not m:
        return []
    return re.findall(r'"([^"]+)"', m.group(1))


def parse_plugin_dirs(root: str) -> list:
    """Read plugin search roots from the generator.

    The generator is the authority on where plugins (incl. nested sub-plugin
    namespaces) legitimately live. Parsing it keeps the gate consistent with the
    composition root instead of duplicating a guess (umbrella blocker B-1).
    """
    roots = list(_parse_string_list(root, "pluginDirs"))
    seen = set(roots)
    for domain in _parse_string_list(root, "nestedPluginDomains"):
        rel = f"internal/component/{domain}/plugins"
        if rel not in seen:
            roots.append(rel)
            seen.add(rel)
    return roots


def nested_namespaces(plugin_dirs: list) -> list:
    """Sub-plugin registries nested under a component (e.g. bgp/plugins).

    These are pluginDirs entries under internal/component/ that are deeper than a
    top-level subsystem (>= 4 path segments). Engine packages inside them are
    sub-plugins of their host and are correctly placed, so the tier check skips
    them.
    """
    return [
        pd
        for pd in plugin_dirs
        if pd.startswith("internal/component/") and pd.count("/") >= 3
    ]


def find_engine_dirs(root: str, nested_ns: list) -> list:
    """Repo-relative dirs (under the two areas) whose non-test code calls
    sdk.NewWithConn, excluding anything inside a nested sub-plugin namespace."""
    engines = []
    for area in ("internal/component", "internal/plugins"):
        area_abs = os.path.join(root, area)
        for dirpath, dirs, files in os.walk(area_abs):
            dirs[:] = [d for d in dirs if d not in (".git", "vendor", "tmp")]
            rel = os.path.relpath(dirpath, root)
            if any(rel == ns or rel.startswith(ns + os.sep) for ns in nested_ns):
                continue
            for f in files:
                if not f.endswith(".go") or f.endswith("_test.go"):
                    continue
                try:
                    txt = open(os.path.join(dirpath, f), errors="ignore").read()
                except OSError:
                    continue
                if "sdk.NewWithConn(" in txt:
                    engines.append(rel)
                    break
    return sorted(engines)


def top_subsystem(rel: str) -> str:
    """Map any package path under the two areas to its top-level subsystem dir,
    e.g. internal/component/ike/engine -> internal/component/ike, and
    internal/plugins/log/cmd -> internal/plugins/log."""
    return "/".join(rel.split("/")[:3])


def engine_subsystems(root: str) -> set:
    """Top-level subsystems containing an sdk.NewWithConn engine (nested sub-plugin
    namespaces from the generator's pluginDirs excluded), used only to LABEL the
    advisory tiers -- the enforced gate uses find_engine_dirs directly."""
    plugin_dirs = parse_plugin_dirs(root)
    nested_ns = nested_namespaces(plugin_dirs)
    return {top_subsystem(e) for e in find_engine_dirs(root, nested_ns)}


def engine_depended(engine_rel: str, module: str, edges: dict) -> bool:
    """True if a feature (another component/plugins package) imports the engine
    package's own subtree. Excludes the engine's own subtree, tests, the generated
    composition root, cmd/ze dispatch, and non-feature trees (core/chaos/test)."""
    pkg = module + "/" + engine_rel
    own = engine_rel + os.sep
    for imported, importers in edges.items():
        if imported != pkg and not imported.startswith(pkg + "/"):
            continue
        for imp in importers:
            if imp.startswith(own) or imp.endswith("_test.go"):
                continue
            if is_registration_importer(imp):
                continue
            if any(imp.startswith(p) for p in NON_FEATURE_PREFIXES):
                continue
            if imp.startswith("internal/component/") or imp.startswith(
                "internal/plugins/"
            ):
                return True
    return False


def engine_misplacements(root: str, module: str, edges: dict) -> dict:
    """dir -> expected_area for every misplaced engine (Path C). Raises on a failed
    pluginDirs parse so the gate fails loud rather than flagging everything."""
    plugin_dirs = parse_plugin_dirs(root)
    if not plugin_dirs:
        raise SystemExit(
            f"{GENERATOR}: could not parse pluginDirs -- gate cannot run safely"
        )
    nested_ns = nested_namespaces(plugin_dirs)
    out = {}
    for eng in find_engine_dirs(root, nested_ns):
        area = (
            "internal/component"
            if eng.startswith("internal/component/")
            else "internal/plugins"
        )
        expected = (
            "internal/component"
            if engine_depended(eng, module, edges)
            else "internal/plugins"
        )
        if expected != area:
            out[eng] = expected
    return out


def read_baseline(root: str) -> set:
    path = os.path.join(root, BASELINE)
    if not os.path.exists(path):
        return set()
    keys = set()
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        keys.add(line.split()[0])
    return keys


def write_baseline(root: str, mis: dict) -> None:
    lines = [
        "# Tier migration baseline -- TRANSITIONAL, not a permanent allowlist.",
        "# Each row is a misplaced engine scheduled to move; the gate FAILS on a NEW",
        "# misplacement and on a STALE entry (one no longer misplaced). An empty file",
        "# means full engine-placement enforcement with zero exceptions.",
        "# See ai/rules/architecture.md and plan/spec-tiers-0-umbrella.md.",
        "# columns: <current-dir>\\t<expected-area>\\t<resolving-child-spec>",
    ]
    for eng in sorted(mis):
        spec = "spec-tiers-2" if mis[eng].endswith("plugins") else "spec-tiers-3"
        lines.append(f"{eng}\t{mis[eng]}\t{spec}")
    out = os.path.join(root, BASELINE)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def load_non_engine_categories(root: str) -> tuple[dict, list]:
    """Parse tier_non_engine_categories.txt.

    Rows are repo-relative package dirs plus a category and free-form rationale:
        internal/component/host  host-service  host APIs + doctor registration

    The manifest is the human-readable source of truth for intentional non-engine
    placements outside the purely mechanical plugin/component/core rules.
    """
    path = os.path.join(root, NON_ENGINE_CATEGORIES)
    rows = {}
    errors = []
    if not os.path.exists(path):
        return rows, [f"{NON_ENGINE_CATEGORIES}: missing non-engine category manifest"]
    for lineno, line in enumerate(open(path, encoding="utf-8"), 1):
        raw = line.strip()
        if not raw or raw.startswith("#"):
            continue
        parts = raw.split(None, 2)
        if len(parts) != 3 or not parts[2].strip():
            errors.append(
                f"{NON_ENGINE_CATEGORIES}:{lineno}: expected '<path> <category> <rationale>'"
            )
            continue
        rel, category, rationale = parts[0], parts[1], parts[2].strip()
        if rel in rows:
            errors.append(f"{NON_ENGINE_CATEGORIES}:{lineno}: duplicate row for {rel}")
            continue
        if category not in LEGAL_NON_ENGINE_CATEGORIES:
            cats = ", ".join(sorted(LEGAL_NON_ENGINE_CATEGORIES))
            errors.append(
                f"{NON_ENGINE_CATEGORIES}:{lineno}: unknown category {category!r}; expected one of {cats}"
            )
            continue
        if category == "planned-violation" and not re.search(
            r"\bspec-[A-Za-z0-9][A-Za-z0-9_.-]*\b", rationale
        ):
            errors.append(
                f"{NON_ENGINE_CATEGORIES}:{lineno}: planned-violation rationale must cite a spec-* reference"
            )
            continue
        rows[rel] = {
            "category": category,
            "rationale": rationale,
            "line": lineno,
        }
    return rows, errors


def non_engine_manifest_required(row: dict) -> bool:
    """True when mechanics cannot classify this non-engine placement alone."""
    if row["is_engine"] or row["is_registered"]:
        return False
    return True


def non_engine_area(rel: str) -> str | None:
    if rel.startswith("internal/component/"):
        return "internal/component"
    if rel.startswith("internal/plugins/"):
        return "internal/plugins"
    return None


def _under(rel: str, prefix: str) -> bool:
    return rel == prefix or rel.startswith(prefix + "/")


def _setup_feature_registration(importer: str) -> bool:
    return importer.startswith("cmd/ze/") and bool(
        re.search(r"/setup_features_[^/]+\.go$", importer)
    )


def valid_non_engine_category(rel: str, category: str, row: dict) -> tuple[bool, str]:
    if category == "framework":
        if rel.startswith("internal/component/"):
            return True, ""
        if rel.startswith("internal/plugins/") and any(
            _setup_feature_registration(imp) for imp in row["registration"]
        ):
            return True, ""
        return (
            False,
            "framework rows under internal/plugins must be setup-feature registrations",
        )
    if category == "host-service":
        if rel.startswith("internal/component/"):
            return True, ""
        return False, "host-service rows are allowed only under internal/component"
    if category == "domain-library":
        if any(_under(rel, prefix) for prefix in DOMAIN_LIBRARY_PREFIXES):
            return True, ""
        allowed = ", ".join(DOMAIN_LIBRARY_PREFIXES)
        return False, f"domain-library rows are allowed only under {allowed}"
    if category == "planned-violation":
        if rel.startswith("internal/component/") or rel.startswith("internal/plugins/"):
            return True, ""
        return (
            False,
            "planned-violation rows are allowed only under internal/component or internal/plugins",
        )
    return False, f"unknown category {category!r}"


def classify_rel(rel: str, module: str, edges: dict, engine_dirs: set) -> dict:
    pkg_prefix = module + "/" + rel
    own_rel_prefix = rel + os.sep
    external, registration, tests = set(), set(), set()
    for imported, importers in edges.items():
        if imported != pkg_prefix and not imported.startswith(pkg_prefix + "/"):
            continue
        for imp in importers:
            if imp.startswith(own_rel_prefix):
                continue
            if imp.endswith("_test.go"):
                tests.add(imp)
            elif is_registration_importer(imp):
                registration.add(imp)
            else:
                external.add(imp)
    is_registered = len(registration) > 0
    is_engine = rel in engine_dirs
    return {
        "external": sorted(external),
        "registration": sorted(registration),
        "tests": sorted(tests),
        "is_registered": is_registered,
        "is_engine": is_engine,
        "core_candidate": len(external) == 0 and not is_registered and not is_engine,
    }


def non_engine_category_errors(root: str, module: str, edges: dict) -> list:
    manifest, errors = load_non_engine_categories(root)
    plugin_dirs = parse_plugin_dirs(root)
    nested_ns = nested_namespaces(plugin_dirs)
    engine_dirs = set(find_engine_dirs(root, nested_ns))
    engines = {top_subsystem(e) for e in engine_dirs}
    audited = {}
    for area in ("internal/component", "internal/plugins"):
        for row in classify(area, root, module, edges, engines):
            audited[f"{area}/{row['name']}"] = (area, row)

    for rel, meta in sorted(manifest.items()):
        area = non_engine_area(rel)
        if area is None:
            errors.append(
                f"{NON_ENGINE_CATEGORIES}:{meta['line']}: {rel} is outside internal/component or internal/plugins"
            )
            continue
        if not os.path.isdir(os.path.join(root, rel)):
            errors.append(
                f"{NON_ENGINE_CATEGORIES}:{meta['line']}: {rel} does not exist"
            )
            continue
        row = (
            audited[rel][1]
            if rel in audited
            else classify_rel(rel, module, edges, engine_dirs)
        )
        category = meta["category"]
        if row["is_engine"]:
            errors.append(
                f"{NON_ENGINE_CATEGORIES}:{meta['line']}: {rel} is an engine; engine placement is mechanical, not a non-engine category"
            )
        ok, reason = valid_non_engine_category(rel, category, row)
        if not ok:
            errors.append(
                f"{NON_ENGINE_CATEGORIES}:{meta['line']}: {rel} uses category {category!r}: {reason}"
            )

    for rel, (_, row) in sorted(audited.items()):
        if non_engine_manifest_required(row) and rel not in manifest:
            errors.append(
                f"{rel}: unclassified non-engine placement; add a {NON_ENGINE_CATEGORIES} row or move it to the mechanical tier"
            )
    return errors


def non_engine_category_gate(root: str, module: str, edges: dict) -> int:
    errors = non_engine_category_errors(root, module, edges)
    if errors:
        print("FAIL: non-engine tier category manifest mismatch:", file=sys.stderr)
        for err in errors:
            print(f"  {err}", file=sys.stderr)
        print(
            "  Rule: ai/rules/architecture.md (non-engine categories are manifest-backed).",
            file=sys.stderr,
        )
        return 2
    manifest, _ = load_non_engine_categories(root)
    print(
        f"OK: non-engine placement categories clean; {len(manifest)} manifest row(s)."
    )
    return 0


# ---------------------------------------------------------------------------
# Core import-direction gate (internal/core must not import upward)
# ---------------------------------------------------------------------------
#
# internal/core is the leaf library tier (ai/rules/architecture.md): it may not
# import internal/component or internal/plugins. The grandfathered violations
# live in a shrink-only baseline at PAIR granularity (importer file + imported
# package), each row annotated with its fix route, so a fixed pair left behind
# is a stale-entry failure and a NEW upward import in an already-baselined file
# is still caught. See plan/spec-layout-0-umbrella.md (child 2).

CORE_IMPORT_BASELINE = "scripts/dev/core_import_baseline.txt"
CORE_AREA_PREFIX = "internal/core/"
CORE_FORBIDDEN = ("internal/component", "internal/plugins")
CORE_FIX_ROUTES = ("hand-fixable", "generator-fixable", "needs-design")


def core_direction_violations(root: str, module: str, edges: dict) -> set:
    """(importer-file, imported-package) pairs where internal/core imports a
    package under internal/component or internal/plugins. Test files count:
    the grandfathered set includes internal/core/ipc/yang_test.go."""
    out = set()
    bases = tuple(module + "/" + p for p in CORE_FORBIDDEN)
    for imported, importers in edges.items():
        if not any(imported == b or imported.startswith(b + "/") for b in bases):
            continue
        rel = imported[len(module) + 1 :]
        for imp in importers:
            if imp.startswith(CORE_AREA_PREFIX):
                out.add((imp, rel))
    return out


def read_core_import_baseline(root: str) -> tuple[set, list]:
    """Parse the shrink-only baseline: '<core-file> <imported-package>
    <fix-route>: <rationale>' rows. Returns (pairs, errors); an illegal fix
    route is an error so nothing can be baselined without a named route."""
    path = os.path.join(root, CORE_IMPORT_BASELINE)
    pairs, errors = set(), []
    if not os.path.exists(path):
        return pairs, errors
    for lineno, line in enumerate(open(path, encoding="utf-8"), 1):
        raw = line.strip()
        if not raw or raw.startswith("#"):
            continue
        parts = raw.split(None, 2)
        if len(parts) != 3:
            errors.append(
                f"{CORE_IMPORT_BASELINE}:{lineno}: expected "
                "'<core-file> <imported-package> <fix-route>: <rationale>'"
            )
            continue
        route = parts[2].split(":", 1)[0].strip()
        if route not in CORE_FIX_ROUTES:
            errors.append(
                f"{CORE_IMPORT_BASELINE}:{lineno}: fix route {route!r} "
                f"not one of {sorted(CORE_FIX_ROUTES)}"
            )
            continue
        pairs.add((parts[0], parts[1]))
    return pairs, errors


def core_direction_gate(root: str, module: str, edges: dict) -> int:
    current = core_direction_violations(root, module, edges)
    baseline, errors = read_core_import_baseline(root)
    if errors:
        print(f"FAIL: {CORE_IMPORT_BASELINE} malformed:", file=sys.stderr)
        for err in errors:
            print(f"  {err}", file=sys.stderr)
        return 2
    new = current - baseline
    stale = baseline - current
    if new:
        print(
            "FAIL: new upward import(s) from internal/core -- wrong direction:",
            file=sys.stderr,
        )
        for imp, pkg in sorted(new):
            print(f"  {imp} imports {pkg}", file=sys.stderr)
        print(
            "  Rule: internal/core is the leaf tier and imports neither "
            "internal/component nor internal/plugins (ai/rules/architecture.md).",
            file=sys.stderr,
        )
        print(
            f"  A deliberate, spec-referenced exception goes in {CORE_IMPORT_BASELINE} "
            "with a fix route (hand-fixable / generator-fixable / needs-design).",
            file=sys.stderr,
        )
    if stale:
        print(
            "FAIL: stale core-import baseline row(s) -- the upward import is "
            f"gone, remove from {CORE_IMPORT_BASELINE}:",
            file=sys.stderr,
        )
        for imp, pkg in sorted(stale):
            print(f"  {imp} imports {pkg}", file=sys.stderr)
    if new or stale:
        return 2
    if current:
        files = sorted({imp for imp, _ in current})
        print(
            f"OK: core import direction clean; {len(current)} pair(s) in "
            f"{len(files)} file(s) baselined (pending fix)."
        )
    else:
        print("OK: core import direction clean; no exceptions (baseline empty).")
    return 0


def run_gate(root: str, module: str, edges: dict) -> int:
    """Combined --check gate: engine placement, non-engine category manifest,
    core import direction, disableable imports, and .golangci.yml manifest
    drift."""
    engine_rc = engine_placement_gate(root, module, edges)
    non_engine_rc = non_engine_category_gate(root, module, edges)
    core_rc = core_direction_gate(root, module, edges)
    dis_rc = disableable_gate(root, module, edges)
    golangci_rc = golangci_drift_gate(root)
    return engine_rc or non_engine_rc or core_rc or dis_rc or golangci_rc


def engine_placement_gate(root: str, module: str, edges: dict) -> int:
    mis = engine_misplacements(root, module, edges)
    baseline = read_baseline(root)
    current = set(mis)
    new = current - baseline
    stale = baseline - current

    if new:
        print("FAIL: new misplaced engine(s) -- wrong module tier:", file=sys.stderr)
        for eng in sorted(new):
            print(f"  {eng}  must move to {mis[eng]}/", file=sys.stderr)
        print(
            "  Rule: ai/rules/architecture.md (engine -> component if a feature "
            "depends on it, else plugins).",
            file=sys.stderr,
        )
        print(
            f"  If this is an intentional, scheduled move, add it to {BASELINE}.",
            file=sys.stderr,
        )
    if stale:
        print(
            "FAIL: stale baseline entry(ies) -- no longer misplaced, remove from "
            f"{BASELINE}:",
            file=sys.stderr,
        )
        for eng in sorted(stale):
            print(f"  {eng}", file=sys.stderr)
    if new or stale:
        return 2

    if current:
        print(
            f"OK: engine placement clean; {len(current)} engine(s) baselined "
            "(pending migration):"
        )
        for eng in sorted(current):
            print(f"  {eng} -> {mis[eng]}/")
    else:
        print("OK: engine placement clean; no exceptions (baseline empty).")
    print(
        "advisory: engine placement is mechanical; intentional non-engine "
        f"framework/host/domain placements are declared in {NON_ENGINE_CATEGORIES}."
    )
    return 0


def _quiet_gate(root: str, module: str, edges: dict) -> int:
    import contextlib
    import io

    with (
        contextlib.redirect_stdout(io.StringIO()),
        contextlib.redirect_stderr(io.StringIO()),
    ):
        return run_gate(root, module, edges)


