// Design: docs/architecture/command-ownership.md — YANG as data, codegen enables folder test
//
// yang_glue generates embed.go + register.go in every yang/ directory that
// contains .yang files. The generated Go glue wires YANG modules into the
// config/yang registry via init().
//
// Usage: go run scripts/codegen/yang_glue.go [--check]
//
//go:build ignore

package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

func main() {
	checkOnly := flag.Bool("check", false, "verify generated files are current without writing them")
	flag.Parse()

	root, err := findModuleRoot()
	if err != nil {
		fatal(err)
	}

	module, err := readModulePath(filepath.Join(root, "go.mod"))
	if err != nil {
		fatal(err)
	}

	dirs, err := discoverYangDirs(filepath.Join(root, "internal"))
	if err != nil {
		fatal(err)
	}

	if len(dirs) == 0 {
		fmt.Fprintln(os.Stdout, "yang_glue: no yang/ directories with .yang files found") //nolint:errcheck // output
		return
	}

	var stale []string
	for _, dir := range dirs {
		yangs, err := listYangFiles(dir)
		if err != nil {
			fatal(err)
		}
		if len(yangs) == 0 {
			continue
		}

		embedContent := generateEmbed(yangs)
		registerContent := generateRegister(yangs, module)

		embedPath := filepath.Join(dir, "embed.go")
		registerPath := filepath.Join(dir, "register.go")

		if *checkOnly {
			if !fileMatchesContent(embedPath, embedContent) {
				stale = append(stale, embedPath)
			}
			if !fileMatchesContent(registerPath, registerContent) {
				stale = append(stale, registerPath)
			}
		} else {
			if err := writeIfChanged(embedPath, embedContent); err != nil {
				fatal(err)
			}
			if err := writeIfChanged(registerPath, registerContent); err != nil {
				fatal(err)
			}
		}
	}

	if *checkOnly {
		if len(stale) > 0 {
			for _, f := range stale {
				fmt.Fprintln(os.Stderr, "stale:", f)
			}
			fatal(fmt.Errorf("%d generated files are stale; run make generate", len(stale)))
		}
		fmt.Fprintln(os.Stdout, "yang_glue:", len(dirs), "yang/ directories are current") //nolint:errcheck // output
		return
	}

	fmt.Fprintln(os.Stdout, "yang_glue: generated glue for", len(dirs), "yang/ directories") //nolint:errcheck // output
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "yang_glue:", err)
	os.Exit(1)
}

func findModuleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found")
		}
		dir = parent
	}
}

func readModulePath(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()

	// A scan that stops early leaves the module directive unseen, and the
	// error below then stops the generator. No file is written from a partial
	// go.mod.
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if strings.HasPrefix(line, "module ") {
			return strings.TrimSpace(strings.TrimPrefix(line, "module")), nil
		}
	}
	return "", fmt.Errorf("module directive not found in %s", path)
}

// discoverYangDirs finds all directories named "yang" under root that contain
// at least one .yang file, excluding test directories.
func discoverYangDirs(internalDir string) ([]string, error) {
	var dirs []string

	err := filepath.WalkDir(internalDir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		if strings.Contains(filepath.ToSlash(path), "/internal/test/") {
			return filepath.SkipDir
		}
		if d.Name() != "yang" {
			return nil
		}
		// Skip internal/component/config/yang — that's the registry package.
		rel, _ := filepath.Rel(internalDir, path)
		if rel == filepath.Join("component", "config", "yang") {
			return filepath.SkipDir
		}
		entries, readErr := os.ReadDir(path)
		if readErr != nil {
			return readErr
		}
		for _, e := range entries {
			if !e.IsDir() && strings.HasSuffix(e.Name(), ".yang") {
				dirs = append(dirs, path)
				return filepath.SkipDir
			}
		}
		return filepath.SkipDir
	})
	if err != nil {
		return nil, err
	}

	sort.Strings(dirs)
	return dirs, nil
}

func listYangFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var yangs []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".yang") {
			yangs = append(yangs, e.Name())
		}
	}
	sort.Strings(yangs)
	return yangs, nil
}

func generateEmbed(yangs []string) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by scripts/codegen/yang_glue.go; DO NOT EDIT.\n")
	buf.WriteString("\n")
	buf.WriteString("package yang\n")
	buf.WriteString("\n")
	buf.WriteString("import _ \"embed\"\n")

	for _, y := range yangs {
		buf.WriteString("\n")
		buf.WriteString("//go:embed " + y + "\n")
		buf.WriteString("var " + yangVarName(y) + " string\n")
	}

	return buf.Bytes()
}

func generateRegister(yangs []string, module string) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by scripts/codegen/yang_glue.go; DO NOT EDIT.\n")
	buf.WriteString("\n")
	buf.WriteString("package yang\n")
	buf.WriteString("\n")
	buf.WriteString("import (\n")
	buf.WriteString("\tconfigyang \"" + module + "/internal/component/config/yang\"\n")
	buf.WriteString(")\n")
	buf.WriteString("\n")
	buf.WriteString("func init() {\n")
	for _, y := range yangs {
		buf.WriteString("\tconfigyang.RegisterModule(\"" + y + "\", " + yangVarName(y) + ")\n")
	}
	buf.WriteString("}\n")

	return buf.Bytes()
}

// yangVarName converts a YANG filename like "ze-host-cmd.yang" to a Go
// variable name like "ZeHostCmdYANG".
func yangVarName(filename string) string {
	name := strings.TrimSuffix(filename, ".yang")
	parts := strings.Split(name, "-")

	var b strings.Builder
	for _, p := range parts {
		if upper, ok := acronyms[strings.ToLower(p)]; ok {
			b.WriteString(upper)
		} else {
			b.WriteString(titleCase(p))
		}
	}
	b.WriteString("YANG")
	return b.String()
}

func titleCase(s string) string {
	if s == "" {
		return s
	}
	runes := []rune(s)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}

