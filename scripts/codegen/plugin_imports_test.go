const pluginImportsTimeout = 60 * time.Second

// VALIDATES: scripts/codegen/plugin_imports.go --check verifies generated imports.
// PREVENTS: changed-file verification failing because build-ignore codegen scripts lack a test package.
func TestPluginImportsCheckRuns(t *testing.T) {
	out := runPluginImportsCheck(t)
	if !strings.Contains(out, "is current") {
		t.Fatalf("plugin_imports.go --check did not report current generated imports:\n%s", out)
	}
}

// VALIDATES: scripts/codegen/plugin_imports.go --check does not mutate internal/component/plugin/all/all.go.
// PREVENTS: verification gates modifying generated files while checking inventory consistency.
func TestPluginImportsCheckModeIsReadOnly(t *testing.T) {
	root := repoRoot(t)
	allGo := filepath.Join(root, "internal", "component", "plugin", "all", "all.go")
	before, err := os.ReadFile(allGo)
	if err != nil {
		t.Fatalf("read all.go before check: %v", err)
	}
	_ = runPluginImportsCheck(t)
	after, err := os.ReadFile(allGo)
	if err != nil {
		t.Fatalf("read all.go after check: %v", err)
	}
	if !bytes.Equal(before, after) {
		t.Fatalf("plugin_imports.go --check mutated all.go")
	}
}

// VALIDATES: nested BNG/VPN component-domain plugin roots are discovered structurally.
// PREVENTS: clustering edge plugins under l2tp/plugins or ike/plugins dropping registrations.
func TestClusterPluginDiscovery(t *testing.T) {
	root := newClusterPluginFixture(t)
	writeFixtureFile(t, root, "internal/component/plugin/all/all.go", generatedAllGoFixture(
		"example.test/cluster/internal/component/ike/plugins/sitevpn",
		"example.test/cluster/internal/component/l2tp/plugins/edgeauth",
	))

	out := runPluginImportsCheckInDir(t, root)
	if !strings.Contains(out, "is current (2 plugins, 0 schemas, 0 rpcs, 0 namespaces, 0 gated groups)") {
		t.Fatalf("plugin_imports.go --check did not count nested cluster plugins:\n%s", out)
	}
}

// VALIDATES: stale generated-file checks include nested component-domain plugin roots.
// PREVENTS: --check passing after a nested clustered plugin was added but all.go was not regenerated.
func TestPluginImportsCheckDetectsStaleClusterPlugin(t *testing.T) {
	root := newClusterPluginFixture(t)
	writeFixtureFile(t, root, "internal/component/plugin/all/all.go", generatedAllGoFixture())

	out, err := runPluginImportsCheckCommand(t, root)
	if err == nil {
		t.Fatalf("plugin_imports.go --check succeeded with stale all.go:\n%s", out)
	}
	if !strings.Contains(out, "all.go is stale; run make generate") {
		t.Fatalf("plugin_imports.go --check did not report stale nested cluster imports:\n%s", out)
	}
}

func runPluginImportsCheck(t *testing.T) string {
	t.Helper()
	return runPluginImportsCheckInDir(t, repoRoot(t))
}

func runPluginImportsCheckInDir(t *testing.T, dir string) string {
	t.Helper()
	out, err := runPluginImportsCheckCommand(t, dir)
	if err != nil {
		t.Fatalf("plugin_imports.go --check failed: %v\n%s", err, out)
	}
	return out
}

func runPluginImportsCheckCommand(t *testing.T, dir string) (string, error) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), pluginImportsTimeout)
	defer cancel()

	cmd := osexec.CommandContext(ctx, "go", "run", filepath.Join(repoRoot(t), "scripts", "codegen", "plugin_imports.go"), "--check")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	return string(out), err
}

func newClusterPluginFixture(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	writeFixtureFile(t, root, "go.mod", "module example.test/cluster\n\ngo 1.26\n")
	writeFixtureFile(t, root, "feature-gates.txt", "")
	writeFixtureFile(t, root, "internal/component/ike/plugins/sitevpn/register.go", "package sitevpn\n")
	writeFixtureFile(t, root, "internal/component/l2tp/plugins/edgeauth/register.go", "package edgeauth\n")
	return root
}

func writeFixtureFile(t *testing.T, root, rel, content string) {
	t.Helper()
	path := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("create fixture dir for %s: %v", rel, err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write fixture %s: %v", rel, err)
	}
}

func generatedAllGoFixture(imports ...string) string {
	var b strings.Builder
	b.WriteString("// Code generated by scripts/codegen/plugin_imports.go; DO NOT EDIT.\n\n")
	b.WriteString("// Package all imports all internal plugins and schema packages,\n")
	b.WriteString("// triggering their init() registration.\n")
	b.WriteString("//\n")
	b.WriteString("// To add a plugin, create internal/component/bgp/plugins/<name>/register.go with an init()\n")
	b.WriteString("// that calls registry.Register(). Then run: make generate\n")
	b.WriteString("package all\n\n")
	b.WriteString("import (\n")
	for _, imp := range imports {
		b.WriteString("\t_ \"")
		b.WriteString(imp)
		b.WriteString("\"\n")
	}
	b.WriteString(")\n\n")
	return b.String()
}

func repoRoot(t *testing.T) string {
	t.Helper()
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatalf("resolve repository root: %v", err)
	}
	return root
}

// VALIDATES: the build-tag constraint logic (ancestorTagsOfImport /
// constraintForImport / constraintGroups) ANDs EVERY ancestor of a package
// nested more than one gate deep and is deterministic on an equal-length
// ancestor collision.
// PREVENTS: a regression to single-parent constraint generation (fail-open: a
// two-level-nested package would drop its grandparent gate and leak that subtree
// back in) or to map-iteration-order-dependent ancestor selection
// (non-deterministic output). Both were raised as gate-11 review findings and
// left unaddressed by gate-12; --selftest is their first executable coverage.
func TestPluginImportsConstraintSelftest(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), pluginImportsTimeout)
	defer cancel()

	script := filepath.Join(repoRoot(t), "scripts", "codegen", "plugin_imports.go")
	out, err := osexec.CommandContext(ctx, "go", "run", script, "--selftest").CombinedOutput()
	if err != nil {
		t.Fatalf("plugin_imports.go --selftest failed: %v\n%s", err, out)
	}
	if !strings.Contains(string(out), "selftest: PASS") {
		t.Fatalf("plugin_imports.go --selftest did not report PASS:\n%s", out)
	}
}
